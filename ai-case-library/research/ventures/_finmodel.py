#!/usr/bin/env python3
"""Финмодель-отправная точка к деке energy-portfolio-deck.html.

Выручку продукта не моделируем: цен и условий контрактов в этой отрасли никто
не раскрывает — проверка 01.09.2026 не нашла ни одной публичной суммы у CHOICE,
Minsait, Itron, Bidgely, GridUnity и Pearl Street. Любая табличка с выручкой
была бы фальшиво-точной.

Модель отвечает на другой вопрос: при каких значениях неизвестных продукт А
окупается на активах партнёра — то есть ЧТО обязан измерить первый шаг.

    python3 _finmodel.py        # печать + перезапись energy-finmodel.md
"""
from pathlib import Path

# ── Рычаги. Всё, что помечено «допущение», пилот и должен заменить фактом. ──

ACTS_PER_YEAR = {"консервативный": 5_000, "базовый": 20_000, "оптимистичный": 50_000}
# Допущение. Порядок взят от «Россети Центр»: свыше 646 000 проверок в год при
# результативности около 1–2% дают несколько тысяч актов. Факт — у партнёра.

AVG_ASSESSED_RUB = 200_000
# Опора: БЭСК (Уфа) — свыше 50 вскрытых счётчиков дали эффект 10 млн ₽, то есть
# около 200 тыс. ₽ на случай. Пермэнерго — средний штраф около 1 млн ₽ по актам
# бездоговорного потребления. Берём нижнюю опору. Допущение.

COLLECTION_NOW = {"консервативный": 0.60, "базовый": 0.40, "оптимистичный": 0.25}
# Ключевая неизвестная. Опоры: SMUD — 23%; округ Фаридабад — 38–51%.
# Чем ВЫШЕ текущая собираемость, тем МЕНЬШЕ места для продукта, поэтому
# высокое значение отнесено к консервативному сценарию.

UPLIFT_PP = {"консервативный": 0.05, "базовый": 0.10, "оптимистичный": 0.15}
# Прирост доли актов, доходящих до оплаты, за счёт устойчивого оформления.
# Прямого референса нет — допущение. Обоснование: основания развала актов
# в обзоре ВС РФ процедурные, то есть устранимые в поле.

TEAM = {"инженеров": 4, "аналитик данных": 1, "инженер-сетевик": 1}
COST_PER_PERSON_MONTH_RUB = 450_000  # Допущение: полная стоимость специалиста.
BUILD_MONTHS = 9                     # До промышленной эксплуатации продукта А.
FIRST_STEP_WEEKS = 2                 # Платный первый шаг из деки.

SCENARIOS = ["консервативный", "базовый", "оптимистичный"]


def money(x):
    return f"{x/1_000_000:,.1f} млн ₽".replace(",", " ")


def compute(s):
    acts = ACTS_PER_YEAR[s]
    assessed = acts * AVG_ASSESSED_RUB
    now = COLLECTION_NOW[s]
    uplift = UPLIFT_PP[s]
    collected_now = assessed * now
    collected_after = assessed * min(now + uplift, 1.0)
    gain = collected_after - collected_now
    team_cost_year = sum(TEAM.values()) * COST_PER_PERSON_MONTH_RUB * 12
    build_cost = sum(TEAM.values()) * COST_PER_PERSON_MONTH_RUB * BUILD_MONTHS
    payback_months = (build_cost / (gain / 12)) if gain else float("inf")
    return {
        "акты в год": f"{acts:,}".replace(",", " "),
        "доначислено за год": money(assessed),
        "собирается сейчас": f"{now:.0%}",
        "прирост доли": f"+{uplift:.0%} п.п.",
        "возвращено дополнительно": money(gain),
        "стоимость команды в год": money(team_cost_year),
        "стоимость разработки": money(build_cost),
        "окупаемость разработки": (f"{payback_months:.1f} мес."
                                   if payback_months < 999 else "не окупается"),
    }


def breakeven():
    """Какой прирост доли окупает команду за год при базовых объёмах."""
    assessed = ACTS_PER_YEAR["базовый"] * AVG_ASSESSED_RUB
    team_cost_year = sum(TEAM.values()) * COST_PER_PERSON_MONTH_RUB * 12
    return team_cost_year / assessed


def main():
    rows = {s: compute(s) for s in SCENARIOS}
    keys = list(rows[SCENARIOS[0]])

    lines = ["# Финмодель-отправная точка: продукт А на активах партнёра", "",
             "Сгенерировано `_finmodel.py`. Правятся только рычаги в начале скрипта.", "",
             "**Выручку продукта не моделируем.** Проверка 01.09.2026 не нашла ни одной",
             "публичной суммы контракта в этой категории — ни у CHOICE, ни у Minsait,",
             "ни у Itron, ни у Bidgely, ни у GridUnity, ни у Pearl Street. Модель считает",
             "не наш доход, а эффект у партнёра: при каких значениях неизвестных продукт",
             "окупается на его собственных сетях.", "",
             "## Сценарии", "",
             "| Показатель | " + " | ".join(SCENARIOS) + " |",
             "|---|" + "---|" * len(SCENARIOS)]
    for k in keys:
        lines.append(f"| {k} | " + " | ".join(rows[s][k] for s in SCENARIOS) + " |")

    be = breakeven()
    lines += ["", "## Как читать эту таблицу", "",
              "Окупаемость в считаные месяцы во всех трёх сценариях — не хорошая",
              "новость, а красный флаг модели. Если бы эффект действительно был",
              "таким, продукт давно бы кто-нибудь построил: категория просматривается",
              "двадцать лет, в ней работают CHOICE, Minsait, Itron и МТС.",
              "",
              "Значит, верно одно из трёх, и что именно — покажет первый шаг:",
              "",
              "- доначисленные суммы в принципе не конвертируются в деньги, и прирост",
              "  доли ничего не меняет, потому что упирается в платёжеспособность;",
              "- прирост доли на порядок меньше заложенного, потому что дефекты",
              "  оформления — не главная причина невзыскания;",
              "- актов и сумм у партнёра существенно меньше, чем в допущении.",
              "",
              "Вся арифметика ниже держится на трёх допущениях и ни на одном факте",
              "с активов партнёра. Показывать её как прогноз нельзя — только как",
              "разметку того, что меряем.", "",
              "## Точка безубыточности", "",
              f"При базовых объёмах команда окупается приростом доли собираемости",
              f"примерно на **{be:.1%} п.п.** Это низкий порог — и именно поэтому",
              "решающей является не эта цифра, а текущая собираемость у партнёра.", "",
              "## Что обязан измерить первый шаг", "",
              "Модель держится на трёх неизвестных, и все три меряются на одном филиале",
              f"за {FIRST_STEP_WEEKS} недели:", "",
              "1. **Сколько актов в год** составляет партнёр — вместо нашего допущения.",
              "2. **Средняя сумма доначисления** — вместо опоры на чужие кейсы.",
              "3. **Какая доля доходит до оплаты и за какой срок** — главная неизвестная.",
              "   Если она уже высокая, продукт А закрывается, и это правильный исход",
              "   первого шага.", "",
              "## Чего в модели нет", "",
              "- Продукты Б и В: у них нет ни цены, ни объёма, ни референса. Считать их",
              "  сейчас — выдавать допущения за план.",
              "- Выручка от внешних продаж. Единственный публичный референс выручки",
              "  чистого игрока в смежной нише — около 3,6 млн $ в год, и это агрегатор,",
              "  а не первичный источник.",
              "- Стоимость доступа к данным и интеграции: зависит от систем партнёра.", ""]

    Path("energy-finmodel.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines[:40]))
    print("\n[записано в energy-finmodel.md]")


if __name__ == "__main__":
    main()
