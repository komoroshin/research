const pptxgen = require("pptxgenjs");
const pres = new pptxgen();
pres.layout = "LAYOUT_WIDE"; // 13.33 x 7.5
pres.lang = "ru-RU";
const W = 13.33, M = 0.6, CW = W - 2 * M;
const C = { dark: "232323", ink: "141A22", lime: "D5F774", blue: "0460F5", subtle: "F7F7F7",
            white: "FFFFFF", cardDark: "343434", ink2: "5C6067", ink3: "8A8E94", wh2: "B8B8B8", wh3: "8C8C8C" };
const F = "Arial", MONO = "Courier New";
let n = 0; const TOTAL = 10;

function base(dark, eyebrow, title, titleSize = 30, titleH = 1.35) {
  n++;
  const s = pres.addSlide();
  s.background = { color: dark ? C.dark : C.white };
  const fg = dark ? C.white : C.ink;
  s.addText("ОКЕАН ТЕХ", { x: W - M - 2.5, y: 0.35, w: 2.5, h: 0.3, align: "right", fontFace: MONO, fontSize: 9,
    color: dark ? C.wh3 : C.ink3, charSpacing: 3, isTextBox: true, margin: 0 });
  if (eyebrow) s.addText(eyebrow.toUpperCase(), { x: M, y: 0.45, w: 8, h: 0.3, fontFace: MONO, fontSize: 9.5,
    color: dark ? C.lime : C.blue, charSpacing: 3, isTextBox: true, margin: 0 });
  s.addText(title, { x: M, y: 0.8, w: CW, h: titleH, fontFace: F, fontSize: titleSize, bold: true, color: fg,
    valign: "top", isTextBox: true, margin: 0, lineSpacingMultiple: 1.0 });
  s.addText(`${n} / ${TOTAL}`, { x: W - M - 1.5, y: 7.0, w: 1.5, h: 0.3, align: "right", fontFace: MONO, fontSize: 9,
    color: dark ? C.wh3 : C.ink3, isTextBox: true, margin: 0 });
  return s;
}
function cards(s, dark, y, h, items, kind) {
  const gap = 0.25, cw = (CW - gap * (items.length - 1)) / items.length;
  items.forEach((it, i) => {
    const x = M + i * (cw + gap);
    s.addShape(pres.shapes.ROUNDED_RECTANGLE, { x, y, w: cw, h, fill: { color: dark ? C.cardDark : C.subtle },
      line: { color: dark ? C.cardDark : C.subtle }, rectRadius: 0.18 });
    if (kind === "stat") {
      s.addText(it.n, { x: x + 0.3, y: y + 0.25, w: cw - 0.6, h: 0.75, fontFace: F, fontSize: 36, bold: true,
        color: dark ? C.white : C.ink, isTextBox: true, margin: 0, valign: "top" });
      s.addText(it.l, { x: x + 0.3, y: y + 1.0, w: cw - 0.6, h: h - 1.15, fontFace: F, fontSize: 11.5,
        color: dark ? C.wh2 : C.ink2, isTextBox: true, margin: 0, valign: "top" });
    } else if (kind === "step") {
      s.addText(it.num.toUpperCase(), { x: x + 0.3, y: y + 0.25, w: cw - 0.6, h: 0.3, fontFace: MONO, fontSize: 9.5,
        color: dark ? C.lime : C.blue, charSpacing: 2, isTextBox: true, margin: 0 });
      s.addText(it.txt, { x: x + 0.3, y: y + 0.6, w: cw - 0.6, h: h - 0.75, fontFace: F, fontSize: 12.5,
        color: dark ? C.white : C.ink, isTextBox: true, margin: 0, valign: "top" });
    } else { // card
      s.addText(it.title, { x: x + 0.3, y: y + 0.25, w: cw - 0.6, h: 0.4, fontFace: F, fontSize: 15, bold: true,
        color: dark ? C.white : C.ink, isTextBox: true, margin: 0 });
      s.addText(it.body, { x: x + 0.3, y: y + 0.7, w: cw - 0.6, h: h - 1.55, fontFace: F, fontSize: 12,
        color: dark ? C.wh2 : C.ink2, isTextBox: true, margin: 0, valign: "top" });
      s.addShape(pres.shapes.LINE, { x: x + 0.3, y: y + h - 0.8, w: cw - 0.6, h: 0, line: { color: dark ? "4A4A4A" : "DDDDDD", width: 0.75 } });
      s.addText(it.line, { x: x + 0.3, y: y + h - 0.7, w: cw - 0.6, h: 0.55, fontFace: F, fontSize: 10.5,
        color: dark ? C.wh3 : C.ink3, isTextBox: true, margin: 0, valign: "top" });
    }
  });
}
function bullets(s, dark, y, h, items) {
  const runs = [];
  items.forEach((it, i) => {
    runs.push({ text: it.b + " ", options: { bold: true, color: dark ? C.white : C.ink } });
    runs.push({ text: it.t, options: { color: dark ? C.white : C.ink, breakLine: i < items.length - 1 } });
  });
  s.addText(runs, { x: M, y, w: CW - 0.6, h, fontFace: F, fontSize: 14, bullet: { indent: 18 }, paraSpaceAfter: 10,
    isTextBox: true, margin: 0, valign: "top", lineSpacingMultiple: 1.15 });
}
function accent(s, dark, y, h, text) {
  s.addText(text, { x: M, y, w: CW - 0.6, h, fontFace: F, fontSize: 14.5, bold: !dark, color: dark ? C.lime : C.ink,
    isTextBox: true, margin: 0, valign: "top", lineSpacingMultiple: 1.15 });
}
function note(s, dark, y, text) {
  s.addText(text, { x: M, y, w: CW - 1.8, h: 0.7, fontFace: F, fontSize: 9.5, color: dark ? C.wh3 : C.ink3,
    isTextBox: true, margin: 0, valign: "top" });
}

