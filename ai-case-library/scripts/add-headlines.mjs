const file = path.join(DATA, 'small-cases.json');
const cases = readJson(file);

const orphans = Object.keys(HEADLINES).filter((id) => !cases.some((c) => c.id === id));
const uncovered = cases.filter((c) => c.metrics?.length && !HEADLINES[c.id]).map((c) => c.id);
if (orphans.length) {
  console.error(COLORS.red('Лишние id в словаре: ' + orphans.join(', ')));
  process.exit(1);
}
if (uncovered.length) {
  console.log(COLORS.yellow('Кейсы с цифрами без headline (получат автосборку): ' + uncovered.join(', ')));
}

const enriched = cases.map((c) => {
  const out = {};
  for (const [k, v] of Object.entries(c)) {
    if (k === 'headline') continue;
    out[k] = v;
    if (k === 'title' && HEADLINES[c.id]) out.headline = HEADLINES[c.id];
  }
  return out;
});

fs.writeFileSync(file, JSON.stringify(enriched, null, 2) + '\n', 'utf8');
