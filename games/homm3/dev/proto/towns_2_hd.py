def thatch(c, cx, ybase, half, ytop, lit, band, shade):
    """соломенная крыша: конус с горизонтальными светлыми полосами (слои соломы), правая грань в тени"""
    c.poly([(cx - half, ybase), (cx, ytop), (cx + half, ybase)], lit)
    c.poly([(cx, ybase), (cx, ytop), (cx + half, ybase)], shade)
    hh = ybase - ytop
    for y in range(ytop + 3, ybase, 5):
        hw = half * (y - ytop) / float(hh)
        rect(c, int(cx - hw), y, int(cx + hw), y + 2, band)

