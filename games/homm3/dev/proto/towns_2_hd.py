def rect(c, x0, y0, x1, y1, col):
    """прямоугольник [x0,x1)×[y0,y1)"""
    c.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], col)


def wall(c, x0, y0, x1, y1, lit, shade, frac=0.68):
    """стена: левая часть освещена, правая треть в тени"""
    rect(c, x0, y0, x1, y1, lit)
    rect(c, int(x0 + (x1 - x0) * frac), y0, x1, y1, shade)


def crenels(c, x0, x1, ytop, h, col, tooth=5, gap=4):
    """зубцы поверх стены: верх стены на ytop, зубцы поднимаются на h"""
    x = x0
    while x + tooth <= x1:
        rect(c, x, ytop - h, x + tooth, ytop, col)
        x += tooth + gap


def window(c, x, y, col, w=5, h=7, arch=True):
    """окно w×h, верх — стрельчатая арка"""
    rect(c, x, y + (2 if arch else 0), x + w, y + h, col)
    if arch: c.poly([(x, y + 2), (x + w / 2.0, y - 0.5), (x + w, y + 2)], col)


def cone(c, cx, ybase, half, ytop, lit, shade, lean=0):
    """конус крыши: основание [cx-half, cx+half] на ybase, вершина (cx+lean, ytop); левая грань светлее"""
    c.poly([(cx - half, ybase), (cx + lean, ytop), (cx + half, ybase)], shade)
    c.poly([(cx - half, ybase), (cx + lean, ytop), (cx + lean, ybase)], lit)


def skull(c, x, y, bone='i', eye='z'):
    """череп 7×7: свод, глазницы, зубы"""
    c.ellipse(x + 3.5, y + 3, 3.5, 3.2, bone)
    rect(c, x + 1, y + 5, x + 6, y + 7, bone)
    rect(c, x + 1, y + 2, x + 3, y + 4, eye); rect(c, x + 4, y + 2, x + 6, y + 4, eye)
    rect(c, x + 2, y + 5, x + 3, y + 7, eye); rect(c, x + 4, y + 5, x + 5, y + 7, eye)   # зубы 1×2


def finish(c):
    """композитор без контура: одиночные висящие пиксели (все 4 соседа другого цвета) красим в цвет
    самого частого соседа — стиль Б их не допускает; отдаём строки"""
    g = c.g
    for y in range(c.h):
        for x in range(c.w):
            v = g[y][x]
            if v == '.': continue
            nb = [c.get(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]
            if v in nb: continue
            best = max(set(nb), key=nb.count)
            g[y][x] = best
    return c.rows()


