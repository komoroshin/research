# ---------- примитивы архитектуры ----------
def rect(c, x0, y0, x1, y1, mat):
    """прямоугольник: столбцы x0..x1-1, строки y0..y1-1 (полуоткрытый, как срезы)"""
    c.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], mat)

def tower(c, x0, x1, y0, y1, face, shade, sw=None, light=None, lw=3):
    """башня-призма: тело face, правая грань темнее (shade, ширина sw), слева световой столбец light (lw)"""
    rect(c, x0, y0, x1, y1, face)
    sw = sw or max(3, (x1 - x0) // 5)
    rect(c, x1 - sw, y0, x1, y1, shade)
    if light: rect(c, x0, y0, x0 + lw, y1, light)

def cone(c, cx, peak, base, half, light, mid, dark):
    """коническая крыша: вершина (плоская, 2 px) на строке peak, основание на base; левая грань light, правая dark"""
    c.poly([(cx - 1, peak), (cx + 1, peak), (cx + half, base), (cx - half, base)], mid)
    c.poly([(cx - 1, peak), (cx - half * 0.45, base), (cx - half, base)], light)
    c.poly([(cx + 1, peak), (cx + half, base), (cx + half * 0.45, base)], dark)

def dome(c, cx, cy, r, light, mid, dark):
    """луковичный купол: эллипс mid, левый блик light, правая тень dark"""
    c.ellipse(cx, cy, r, r, mid)
    c.ellipse(cx - r * 0.35, cy - r * 0.15, r * 0.45, r * 0.6, light)
    c.poly([(cx + r * 0.35, cy - r), (cx + r + 1, cy - r * 0.3), (cx + r + 1, cy + r * 0.3), (cx + r * 0.35, cy + r + 1)], dark)

def window(c, x, y, mat, w=4, h=6, top=None):
    """окно w×h; top — цвет верхних двух строк (свет купола/арки)"""
    rect(c, x, y, x + w, y + h, mat)
    if top: rect(c, x, y, x + w, y + 2, top)

def crenels(c, x0, x1, ybot, mat, w=6, gap=4, h=5):
    """зубцы на стене: от x0 шагом w+gap, высота h, нижняя строка ybot (стена ниже)"""
    x = x0
    while x + w <= x1:
        rect(c, x, ybot - h, x + w, ybot, mat)
        x += w + gap

def arch(c, cx, ybot, w, h, mat):
    """арочный проём: прямоугольник + полукруг сверху; низ на строке ybot (не включая)"""
    r = w / 2.0
    rect(c, int(cx - r), int(ybot - h + r), int(cx + r), ybot, mat)
    c.ellipse(cx, ybot - h + r, r, r, mat)

def horn(c, xb0, xb1, ybase, xt, ytop, mat):
    """рог/шип: основание xb0..xb1 на ybase, острие (2 px) у (xt, ytop)"""
    c.poly([(xb0, ybase), (xb1, ybase), (xt + 1, ytop), (xt - 1, ytop)], mat)

def flame(c, cx, ybase, h, half, outer, core):
    """язык пламени: наружный цвет outer, ядро core"""
    c.poly([(cx - half, ybase), (cx + half, ybase), (cx + half * 0.3, ybase - h * 0.55), (cx + 1, ybase - h), (cx - 1, ybase - h), (cx - half * 0.3, ybase - h * 0.55)], outer)
    c.poly([(cx - half * 0.5, ybase), (cx + half * 0.5, ybase), (cx + 1, ybase - h * 0.5), (cx - 1, ybase - h * 0.5)], core)

def finish(c):
    return [r.replace('k', '.') for r in c.rows()]   # контур не используем — на всякий случай

