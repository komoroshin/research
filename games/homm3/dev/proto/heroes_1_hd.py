W, H = 48, 52

# ---------- конь: масти ----------
# body — основной тон, dark — тень (круп, брюхо, дальние ноги), hoof — копыта, mane — грива/хвост, mane_tip — кончики гривы (огонь)
HORSES = {
    'bay':   dict(body='n', dark='N', hoof='D', mane='D', mane_tip=None, eye='k'),   # гнедой
    'grey':  dict(body='e', dark='E', hoof='u', mane='E', mane_tip=None, eye='k'),   # серый
    'white': dict(body='L', dark='l', hoof='e', mane='l', mane_tip=None, eye='k'),   # белый
    'black': dict(body='u', dark='z', hoof='E', mane='F', mane_tip='f', eye='r'),    # чёрный с огненной гривой (Инферно)
}

def horse(c, m):
    """Конь в профиль, смотрит вправо: тело, круп, грудь, шея, голова, уши, грива, четыре ноги, хвост.
    Ноги стоят на самой нижней строке (y = 51)."""
    body, dark, hoof, mane, tip = m['body'], m['dark'], m['hoof'], m['mane'], m['mane_tip']
    c.line(10, 30, 4, 45, mane, th=3)                            # хвост
    c.ellipse(4, 45, 2.5, 2.5, mane)
    if tip: c.ellipse(4, 46, 1.8, 2.2, tip)                      # огненный кончик хвоста
    c.ellipse(22, 34, 13, 7, body)                               # корпус
    c.ellipse(14, 36, 7, 5.5, dark)                              # круп в тени
    c.ellipse(24, 38.5, 10, 3, dark)                             # брюхо
    c.ellipse(33, 31.5, 6, 6, body)                              # грудь
    c.ellipse(38, 24, 5, 8.5, body, rot=-0.55)                   # шея
    c.ellipse(43, 14.5, 5, 4.2, body)                            # голова
    c.ellipse(46.5, 16, 2.4, 2, dark)                            # морда
    c.poly([(39.5, 11), (41, 6.5), (43.5, 11)], body)            # ухо
    c.feathers([(33, 18), (39.5, 10)], mane, 2.2, (-0.35, -0.8), tip_c=tip)   # грива
    # ноги: дальние темнее, ближние светлее; копыта на строках 48..51
    for x0, mat in ((9, dark), (16, body), (27, dark), (34, body)):   # между ближней и дальней — просвет в 1 px
        c.poly([(x0, 38), (x0 - 1, 49), (x0 + 4, 49), (x0 + 5, 38)], mat)
        c.poly([(x0 - 1, 48), (x0 + 5, 48), (x0 + 5, 52), (x0 - 1, 52)], hoof)

def blanket(c):
    """Попона под всадником — ТОЛЬКО b (свет) и B (тень). Свисает по боку коня, видна спереди и сзади от всадника."""
    c.poly([(13, 26), (33, 26), (32, 37), (14, 37)], 'b')
    c.poly([(13, 33), (33, 33), (32, 37), (14, 37)], 'B')        # нижняя кромка в тени
    c.poly([(13, 26), (16, 26), (17, 37), (14, 37)], 'B')        # задняя кромка

def rider_base(c, cloth, cloth_dark, skin, skin_dark, boot):
    """Всадник верхом: ближняя нога в стремени, торс, плечи, шея, голова (без головного убора)."""
    c.poly([(21, 27), (19, 38), (24, 39), (26, 29)], cloth)      # нога
    c.ellipse(21.5, 39.5, 3.2, 2, boot)                          # сапог
    c.poly([(20, 15), (28, 15), (30, 28), (18, 28)], cloth)      # торс
    c.poly([(18, 22), (23, 22), (23, 28), (18, 28)], cloth_dark) # тень на спине
    c.ellipse(24, 16, 5.5, 2.5, cloth)                           # плечи
    c.poly([(22, 11), (27, 11), (27, 15), (22, 15)], skin_dark)  # шея
    c.ellipse(24.5, 9, 4, 4.5, skin)                             # голова
    c.ellipse(26, 9.5, 2.5, 3, skin_dark)                        # тень на лице у скулы — снимается убором/лицом ниже
    c.ellipse(25.5, 9.5, 2.2, 2.6, skin)

def arm(c, cloth, skin, x1=31, y1=22):
    """Ближняя рука вперёд от плеча к кисти."""
    c.line(27, 18, x1, y1, cloth, th=2.5)
    c.ellipse(x1 + 0.5, y1 + 0.5, 1.8, 1.8, skin)

def finish(c, eyes):
    """Снимаем контур композитора (стиль Б без контура), ставим глаза 'k'/цвет точечно, чистим одиночные пиксели."""
    c.outline(between=set())
    g = [list(r.replace('k', '.')) for r in c.rows()]
    for x, y, col in eyes:
        g[y][x] = col
    return despeckle(g, keep=set((x, y) for x, y, _ in eyes))

def despeckle(g, keep=()):
    """Одиночные пиксели (без соседа того же цвета среди восьми) — в цвет большинства соседей; дырки в 1 пиксель — заливаем.
    keep — координаты глаз, их не трогаем."""
    h, w = len(g), len(g[0])
    def get(x, y): return g[y][x] if 0 <= x < w and 0 <= y < h else '.'
    for _ in range(2):
        for y in range(h):
            for x in range(w):
                col = g[y][x]
                n8 = [get(x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1) if dx or dy]
                n4 = [get(x + 1, y), get(x - 1, y), get(x, y + 1), get(x, y - 1)]
                if col == '.':
                    if all(v != '.' for v in n4): g[y][x] = Counter(n4).most_common(1)[0][0]
                elif (x, y) not in keep and col not in n8:
                    filled = [v for v in n4 if v != '.']
                    g[y][x] = Counter(filled).most_common(1)[0][0] if len(filled) >= 3 else '.'
    return [''.join(r) for r in g]

# ---------- рыцарь: гнедой конь, стальные латы, шлем с красным плюмажем, поднятый меч ----------
def knight():
    c = Canvas(W, H); horse(c, HORSES['bay']); blanket(c)
    rider_base(c, 'e', 'E', 's', 'S', 'E')
    c.poly([(20, 15), (28, 15), (30, 28), (18, 28)], 'e')        # латы (гладкая кираса)
    c.poly([(19, 21), (29, 21), (29, 23), (19, 23)], 'E')        # пояс
    c.ellipse(24.5, 8, 4.8, 5, 'e')                              # шлем
    c.ellipse(24.5, 7, 3, 2.5, 'l')                              # блик
    c.poly([(21, 8), (29, 8), (29, 10), (21, 10)], 'z')          # щель забрала
    c.feathers([(23, 2), (27, 1.5)], 'r', 2.0, (0, -0.6))        # плюмаж
    c.ellipse(29, 17, 2.5, 2.5, 'l')                             # наплечник
    arm(c, 'e', 's', 31, 21)
    c.line(32, 21, 40, 4, 'l', th=2.5)                           # меч поднят
    c.line(33, 20, 40, 5, 'w', th=1)
    c.poly([(29, 19), (35, 17), (36, 20), (30, 22)], 'Y')        # гарда
    return finish(c, [(43, 13, 'k'), (44, 13, 'k')])

