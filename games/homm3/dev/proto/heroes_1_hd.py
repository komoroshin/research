# ---------- следопыт: серый конь, зелёный капюшон, кожаная куртка, лук за плечом ----------
def ranger():
    c = Canvas(W, H); horse(c, HORSES['grey']); blanket(c)
    rider_base(c, 'd', 'N', 's', 'S', 'N')
    c.poly([(21, 15), (28, 15), (30, 28), (19, 28)], 'd')        # кожаная куртка
