def knight_a():
    """Оррин: стальной шлем с поднятым забралом, красный гребень, латы, гладко выбрит"""
    c = canvas(BG_CASTLE)
    shoulders(c, 'e', 'E')                                   # латные наплечники
    rect(c, 0, 40, 47, 41, 'l'); rect(c, 0, 45, 47, 46, 'E')  # рёбра лат
    collar_v(c, 'l', 34, 7, 6); collar_v(c, 'e', 35, 5, 4)   # горжет
    neck(c, 's', 'S')
    head(c, 's', 'S', cy=19, rx=12, ry=12.5)
    c.poly([(15, 27), (19, 31), (24, 32), (30, 31), (34, 27), (33, 31), (24, 34), (16, 31)], 'S')   # тень под челюстью (без бороды — иначе читается как маска)
    brows(c, 'N', 15, 2)
    eyes(c, 18)
    nose(c, 'S')
    mouth(c, 'R', 26, 21, 27)
    # шлем: купол выше линии бровей, налобная кромка, нащёчники
    clipped(c, lambda t: t.ellipse(24, 12, 14, 12, 'e'), ymax=13)
    clipped(c, lambda t: t.ellipse(21, 11, 12, 10.5, 'l'), ymax=9)
    rect(c, 9, 12, 38, 14, 'E')                              # налобная кромка (тень поднятого забрала)
    c.poly([(9, 14), (15, 14), (16, 30), (11, 27)], 'e'); c.poly([(32, 14), (38, 14), (36, 27), (31, 30)], 'E')   # нащёчники
    rect(c, 10, 15, 13, 26, 'l')                             # блик на левом нащёчнике
    c.ellipse(24, 2, 5, 5, 'r'); c.ellipse(23, 1, 3, 3.5, 'o')       # плюмаж-гребень
    return c

