W = H = 48
PAINT = {'silDome': 0, 'rim': 0, 'ao': 0.08}   # плоское освещение: без купола по квадрату и без ободка

# ---------- примитивы ----------
def rect(c, x0, y0, x1, y1, col):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1): c.put(x, y, col)

def clipped(c, fn, ymin=-99, ymax=99, xmin=-99, xmax=99):
    """рисует fn на временном холсте и переносит только окно [xmin..xmax]×[ymin..ymax]"""
    t = Canvas(W, H); fn(t)
    for y in range(max(0, ymin), min(H, ymax + 1)):
        for x in range(max(0, xmin), min(W, xmax + 1)):
            if t.g[y][x] != '.': c.put(x, y, t.g[y][x])

def mirror_poly(pts):
    return [(47 - x, y) for x, y in pts]

# ---------- части портрета ----------
def canvas(bg):
    c = Canvas(W, H); rect(c, 0, 0, W - 1, H - 1, bg); return c

def shoulders(c, col, dark, top=34):
    """плечи шире кадра: тёмный эллипс, поверх — светлый со сдвигом влево-вверх (тень справа и снизу)"""
    c.ellipse(24, top + 24, 40, 24, dark)
    c.ellipse(21, top + 23, 40, 24, col)

def neck(c, skin, shade, x0=19, x1=28, y0=26, y1=37):
    rect(c, x0, y0, x1, y1, skin)
    rect(c, x1 - 2, y0, x1, y1, shade)          # тень справа
    rect(c, x0, y0, x1, y0 + 4, shade)          # тень под подбородком

def head(c, skin, shade, cx=24, cy=18.5, rx=12, ry=13):
    """лицо: эллипс тени и поверх — эллипс кожи со сдвигом влево-вверх (свет слева-сверху)"""
    c.ellipse(cx, cy, rx, ry, shade)
    c.ellipse(cx - 1.2, cy - 0.8, rx - 0.6, ry - 0.4, skin)

def eyes(c, y=18, lx=18, rx=29, white='w', pupil='k', under='u'):
    """белок 3×2, зрачок — одиночный k + графитовый пиксель под ним (двойной тёмный пиксель конвейер не размоет)"""
    for ex in (lx, rx):
        rect(c, ex - 1, y, ex + 1, y + 1, white)
        c.put(ex, y, pupil); c.put(ex, y + 1, under)

def brows(c, col, y=15, thick=2, lx=(15, 20), rx=(27, 32)):
    rect(c, lx[0], y, lx[1], y + thick - 1, col)
    rect(c, rx[0], y, rx[1], y + thick - 1, col)

def nose(c, shade, x=24, y0=19, y1=24):
    rect(c, x, y0, x + 1, y1, shade)             # тень правой стороны носа
    rect(c, x - 2, y1, x + 1, y1, shade)         # кончик

def mouth(c, col, y=26, x0=20, x1=27, lower=None):
    rect(c, x0, y, x1, y, col)
    if lower: rect(c, x0 + 1, y + 1, x1 - 1, y + 1, lower)

def hair_top(c, col, cy=13.5, rx=13.5, ry=12):
    """шапка волос за головой (рисуется до лица) — видна над лбом и у висков"""
    c.ellipse(24, cy, rx, ry, col)

def fringe(c, col, pts=None):
    """чёлка поверх лба"""
    c.poly(pts or [(12, 13), (12, 7), (18, 4), (30, 4), (36, 7), (36, 13), (33, 9), (28, 11), (24, 8), (19, 11), (15, 9)], col)

def hair_long(c, col, shade, bottom=44, inner=14):
    """длинные волосы по обе стороны до плеч (рисуются после плеч, до лица)"""
    for pts in ([(11, 12), (8, 26), (6, bottom), (inner + 2, bottom), (inner, 26), (13, 14)],):
        c.poly(pts, shade); c.poly(mirror_poly(pts), shade)
        c.poly([(x + 1, y) for x, y in pts], col); c.poly([(x - 1, y) for x, y in mirror_poly(pts)], col)

def hood(c, col, shade, hi=None, top=7, rx=16.5):
    """капюшон: тёмный «мешок» за головой до плеч (рисуется до лица) — потом hood_front"""
    c.ellipse(24, 17, rx, 17, shade)
    c.ellipse(23, 16, rx - 0.8, 16.5, col)
    for pts in ([(8, 17), (3, 46), (15, 46), (13, 30), (11, 18)],):
        c.poly(pts, col); c.poly(mirror_poly(pts), shade)

def hood_front(c, col, shade, y=7, ry=7.5, rx=15.5):
    """передний край капюшона над лбом"""
    c.ellipse(24, y, rx, ry, shade)
    c.ellipse(23, y - 0.6, rx - 0.6, ry - 0.6, col)

def wreath(c, cols, cx=24, cy=18.5, r=12.5, a0=195, a1=345, n=7):
    """венок из листьев по верхней дуге головы"""
    for i in range(n):
        a = math.radians(a0 + (a1 - a0) * i / (n - 1))
        x, y = cx + r * math.cos(a), cy + r * math.sin(a)
        c.ellipse(x, y, 3.2, 2.2, cols[i % len(cols)], rot=a + math.pi / 2)

def star(c, x, y, col):
    """звёздочка 3×3 крестом (плюс) — деталь крупнее одиночного пикселя"""
    rect(c, x - 1, y, x + 1, y, col); rect(c, x, y - 1, x, y + 1, col); c.put(x, y, col)

def collar_v(c, col, top=34, w=6, depth=8):
    """V-образный вырез/воротник"""
    c.poly([(24 - w, top), (24 + w, top), (24, top + depth)], col)

