def bow(c, mirror=False):
    """лук за правым плечом: дуга из тёмного дерева и тетива"""
    pts = [(40, 0), (44, 12), (45, 24), (43, 36)]
    if mirror: pts = mirror_poly(pts)
    for i in range(len(pts) - 1):
        (x0, y0), (x1, y1) = pts[i], pts[i + 1]
        c.line(x0, y0, x1, y1, 'N', th=3)
    s0, s1 = pts[0], pts[-1]
    c.line(s0[0] - 3, s0[1] + 1, s1[0] - 3, s1[1] - 1, 'w')

