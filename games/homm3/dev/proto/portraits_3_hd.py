def despeckle(rows):
    """одиночный пиксель (все 4 соседа другого цвета, кроме зрачков k) → цвет самого частого соседа"""
    g = [list(r) for r in rows]
    for y in range(H):
        for x in range(W):
            col = g[y][x]
            if col == 'k': continue
            nb = [g[y + dy][x + dx] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)) if 0 <= x + dx < W and 0 <= y + dy < H]
            if all(n != col for n in nb): g[y][x] = max(set(nb), key=nb.count)
    return [''.join(r) for r in g]

