W = H = 48

# ---------- общие помощники ----------
def canvas(bg):
    c = Canvas(W, H)
    c.g = [[bg] * W for _ in range(H)]
    return c

def rect(c, x0, y0, x1, y1, col):
    """закрашенный прямоугольник [x0..x1]×[y0..y1] включительно"""
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1): c.put(x, y, col)

def shoulders(c, col, y=34, shade=None):
    """плечи шире кадра: трапеция от строки y до низа; shade — тень под подбородком"""
    c.poly([(-10, 48), (-10, y + 8), (12, y), (36, y), (58, y + 8), (58, 48)], col)
    if shade: rect(c, 17, y, 30, y + 1, shade)

def neck(c, col, x0=19, x1=28, y0=26, y1=36):
    rect(c, x0, y0, x1, y1, col)

def head(c, skin, cx=24, cy=19, rx=12, ry=13):
    c.ellipse(cx, cy, rx, ry, skin)

def ears(c, skin, cx=24, y=21, rx=12):
    c.ellipse(cx - rx + 0.5, y, 2.2, 3.2, skin); c.ellipse(cx + rx - 0.5, y, 2.2, 3.2, skin)

def eyes(c, y=19, lx=16, rx=28, white='w', pupil='k', wide=4):
    """глаза: белки wide×2 + зрачок 2×2 в середине"""
    rect(c, lx, y, lx + wide - 1, y + 1, white); rect(c, rx, y, rx + wide - 1, y + 1, white)
    rect(c, lx + wide // 2 - 1, y, lx + wide // 2, y + 1, pupil)
    rect(c, rx + wide // 2 - 1, y, rx + wide // 2, y + 1, pupil)

def brows(c, col, y=16, lx=16, rx=27, w=5, h=2, tilt=0):
    """брови w×h; tilt=1 — сдвинуть внутренние концы вниз (сердитые), -1 — вверх"""
    rect(c, lx, y, lx + w - 1, y + h - 1, col); rect(c, rx, y, rx + w - 1, y + h - 1, col)
    if tilt:
        rect(c, lx + w - 2, y + tilt, lx + w - 1, y + h - 1 + tilt, col)
        rect(c, rx, y + tilt, rx + 1, y + h - 1 + tilt, col)

def nose(c, shade, x=23, y=21, h=4):
    rect(c, x, y, x + 1, y + h - 1, shade)
    rect(c, x - 1, y + h - 1, x + 2, y + h - 1, shade)

def mouth(c, col, y=27, x0=20, x1=27, h=1):
    rect(c, x0, y, x1, y + h - 1, col)

def beard(c, col, cx=24, cy=30, rx=11, ry=6, cut=27):
    """борода: часть эллипса не выше строки cut (начинается под ртом)"""
    t = Canvas(W, H); t.ellipse(cx, cy, rx, ry, col)
    for y in range(cut, H):
        for x in range(W):
            if t.g[y][x] != '.': c.put(x, y, col)

def moustache(c, col, y=25, x0=19, x1=28):
    rect(c, x0, y, x1, y + 1, col)

