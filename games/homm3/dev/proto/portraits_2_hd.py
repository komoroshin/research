W = H = 48
PAINT = {'silDome': 0, 'rim': 0, 'ao': 0.08}   # плоское освещение: портрет — квадрат, купол по силуэту не нужен

# ---------- помощники ----------
def new(bg):
    """холст, целиком залитый фоном фракции"""
    c = Canvas(W, H)
    for y in range(H):
        for x in range(W): c.put(x, y, bg)
    return c

def rect(c, x0, y0, x1, y1, col):
    """прямоугольник включительно по обоим углам"""
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1): c.put(x, y, col)

def shoulders(c, col, top=37):
    """плечи шире кадра: трапеция + скруглённые плечевые ядра"""
    c.poly([(8, top), (40, top), (56, 48), (-8, 48)], col)
    c.ellipse(5, top + 6, 11, 6, col); c.ellipse(43, top + 6, 11, 6, col)

def neck(c, col, x0=19, x1=29, y0=27, y1=41):
    c.poly([(x0, y0), (x1, y0), (x1 + 1, y1), (x0 - 1, y1)], col)

def head(c, col, cx=24, cy=20, rx=12, ry=13):
    c.ellipse(cx, cy, rx, ry, col)

def jaw(c, col, wide=True):
    """мужская челюсть: расширяем нижнюю половину лица"""
    if wide: c.poly([(13, 20), (35, 20), (33, 31), (24, 34), (15, 31)], col)
    else: c.poly([(14, 20), (34, 20), (31, 30), (24, 33), (17, 30)], col)

def eyes(c, y=19, white='w', pupil='k', lx=17, rx=28):
    """два глаза 3×2: белок + зрачок 1×2 в середине"""
    for x0 in (lx, rx):
        rect(c, x0, y, x0 + 2, y + 1, white)
        rect(c, x0 + 1, y, x0 + 1, y + 1, pupil)

def brows(c, col, y=16, th=2, lx=16, rx=27, w=5):
    rect(c, lx, y, lx + w - 1, y + th - 1, col); rect(c, rx, y, rx + w - 1, y + th - 1, col)

def nose(c, col, y=21):
    rect(c, 23, y, 24, y + 4, col); rect(c, 22, y + 4, 25, y + 5, col)

def mouth(c, col, y=28, x0=20, x1=27):
    rect(c, x0, y, x1, y + 1, col)

def clean(c):
    """одиночных пикселей быть не должно: пиксель без единого соседа своего цвета красим в цвет большинства соседей"""
    g = c.g
    for y in range(H):
        for x in range(W):
            col = g[y][x]
            nb = [g[y + dy][x + dx] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)) if 0 <= x + dx < W and 0 <= y + dy < H]
            if all(n != col for n in nb): g[y][x] = max(set(nb), key=nb.count)
    return c.rows()

