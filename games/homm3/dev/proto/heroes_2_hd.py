def block(name, rows, comment, unit=2):
    """Блок для defineMany с hd: true, unit: 2 (копия помощника из castle_hd, чтобы не пересобирать чужие файлы)."""
    w = max(len(r) for r in rows); rows = [(r + '.' * w)[:w] for r in rows]
    body = '\n'.join("        '%s'," % r for r in rows)
    return "    /* %s (%d×%d) */\n    %s: {\n      hd: true, unit: %d,\n      rows: [\n%s\n      ],\n    },\n" % (comment, w, len(rows), name, unit, body)


def despeckle(rows, passes=2):
    """Убирает одиночные пиксели: пиксель без соседа того же цвета (по 4 сторонам) красим в самый частый цвет соседей."""
    g = [list(r) for r in rows]
    h, w = len(g), len(g[0])
    for _ in range(passes):
        changed = False
        for y in range(h):
            for x in range(w):
                c = g[y][x]
                if c in '.k': continue
                nb = [g[y + dy][x + dx] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)) if 0 <= x + dx < w and 0 <= y + dy < h]
                if c in nb: continue
                fill = [n for n in nb if n != '.']
                g[y][x] = Counter(fill).most_common(1)[0][0] if fill else '.'
                changed = True
        if not changed: break
    return [''.join(r) for r in g]


def finish(c, eyes):
    """Снимаем автоконтур (k → прозрачный), чистим одиночные пиксели, ставим глаза k."""
    c.outline(between=set())
    rows = despeckle([r.replace('k', '.') for r in c.rows()])
    g = [list(r) for r in rows]
    for x, y in eyes: g[y][x] = 'k'
    return despeckle([''.join(r) for r in g])   # второй проход: глаз мог отколоть одиночный пиксель глазницы; k не трогаем


