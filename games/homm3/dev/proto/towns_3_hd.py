c = Canvas(W, H)
rect(c, 2, 95, 109, 95, 'E')                                # фундамент
# боковые цеха: кирпич + медная крыша
for x0 in (6, 74):
    x1 = x0 + 31                                             # цеха вплотную к корпусу — без щели до земли
    tower(c, x0, x1, 58, 94, 'T', 'S', sw=6)
    c.poly([(x0 - 2, 59), (x1 + 3, 59), (x1 - 4, 46), (x0 + 5, 46)], 'O')   # медная крыша
    rect(c, x0 + 5, 46, x1 - 5, 48, 'o')                     # медный блик по коньку
