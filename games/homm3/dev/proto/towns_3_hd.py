# -*- coding: utf-8 -*-
"""Сборка js/view/sprites_towns_3_hd.js: города Сопряжения, Бухты и Фабрики на карте приключений
в крупной сетке 112×96 (unit 2 → на экране 56×48), стиль Б — без контурной линии, форму держат тона.
Главная башня по центру, её плоский верх на строке 22 (флаг ставит движок), боковые башни выше —
но не по центру. Вся архитектура — композитором (poly/ellipse), окна и зубцы — циклами."""
import io, os, sys
sys.path.insert(0, os.path.dirname(__file__))
from compose import Canvas
from castle_hd import rows_from, pad, block, stretch   # общие помощники (castle_hd при импорте пересобирает свой файл — это безвредно)

W, H = 112, 96

def rect(c, x0, y0, x1, y1, mat):
    """прямоугольник включительно x0..x1, y0..y1"""
    c.poly([(x0, y0), (x1 + 1, y0), (x1 + 1, y1 + 1), (x0, y1 + 1)], mat)

def tower(c, x0, x1, y0, y1, mat, shade, sw=None):
    """башня-параллелепипед: тело mat, правая грань темнее (shade) шириной sw"""
    rect(c, x0, y0, x1, y1, mat)
    sw = sw or max(3, (x1 - x0 + 1) // 5)
    rect(c, x1 - sw + 1, y0, x1, y1, shade)

def cone(c, x0, x1, ybase, ytop, mat, shade):
    """конус крыши: основание x0..x1 на ybase, вершина на ytop; правая половина темнее"""
    cx = (x0 + x1 + 1) / 2.0
    c.poly([(x0, ybase + 1), (cx, ytop), (x1 + 1, ybase + 1)], mat)
    c.poly([(cx, ybase + 1), (cx, ytop), (x1 + 1, ybase + 1)], shade)

def window(c, x, y, mat, w=5, h=7):
    rect(c, x, y, x + w - 1, y + h - 1, mat)

def crenels(c, x0, x1, y, mat, w=5, gap=4, h=4):
    """зубцы над стеной: от x0 шагом w+gap, высота h, нижняя строка y (стена начинается с y+1)"""
    x = x0
    while x + w - 1 <= x1:
        rect(c, x, y - h + 1, x + w - 1, y, mat)
        x += w + gap

def gate(c, cx, ybot, w, h, mat):
    """арочный проём: прямоугольник + полукруг сверху"""
    rect(c, cx - w // 2, ybot - h + w // 2, cx + w // 2, ybot, mat)
    c.ellipse(cx + 0.5, ybot - h + w // 2 + 0.5, w / 2.0 + 0.5, w / 2.0 + 0.5, mat)

def crystal(c, cx, ytip, ymid, ybot, hw, mat, shade):
    """кристалл-шпиль: ромб с вершиной ytip, самой широкой частью на ymid (полуширина hw), низом ybot; правая половина темнее"""
    c.poly([(cx, ytip), (cx + hw, ymid), (cx, ybot), (cx - hw, ymid)], mat)
    c.poly([(cx, ytip), (cx + hw, ymid), (cx, ybot)], shade)

def finish(c):
    """стиль Б: контур не нужен — только чистим одиночные пиксели по краям"""
    rows = [list(r) for r in c.rows()]
    def get(x, y): return rows[y][x] if 0 <= x < W and 0 <= y < H else '.'
    for y in range(H):
        for x in range(W):
            ch = rows[y][x]
            if ch == '.': continue
            n = sum(1 for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)) if get(x + dx, y + dy) != '.')
            if n <= 1: rows[y][x] = '.'
    return [''.join(r) for r in rows]

# =====================================================================================
# Сопряжение: белый замок стихий — центральный белый донжон с сиреневыми окнами, по бокам
# серые пилоны, на которых стоят кристаллы воды (голубой) и огня (оранжевый); у подножия —
# земляной (оливковый) и воздушный (сиреневый) кристаллы, над стенами парят камни.
# =====================================================================================
c = Canvas(W, H)
rect(c, 4, 95, 107, 95, 'E')                                # фундамент
# крепостная стена
rect(c, 4, 66, 107, 94, 'l')
crenels(c, 6, 106, 65, 'l', w=5, gap=5, h=4)
rect(c, 4, 66, 107, 68, 'e')                                 # тёмный карниз под зубцами
# боковые пилоны стихий
for x0 in (8, 82):
    x1 = x0 + 21
    tower(c, x0, x1, 44, 94, 'e', 'E', sw=5)
    rect(c, x0 - 1, 42, x1 + 1, 45, 'E')                    # тёмная капитель
crystal(c, 19, 4, 26, 46, 8, 'c', 'C')                      # кристалл воды (слева)
crystal(c, 93, 4, 26, 46, 8, 'f', 'o')                      # кристалл огня (справа)
rect(c, 17, 10, 19, 24, 'v')                                # блик на воде
rect(c, 91, 10, 93, 24, 'y')                                # блик на огне
# главная белая башня: плоский верх на строке 22, над ней ничего (флаг движка)
tower(c, 40, 71, 25, 94, 'w', 'e', sw=6)                     # правая грань серая: иначе сливалась со стеной 'l'
rect(c, 38, 22, 73, 25, 'l')                                # карниз-площадка
rect(c, 38, 26, 73, 27, 'e')                                # тень под карнизом
for y in (32, 48, 64):                                       # сиреневые окна
    window(c, 46, y, 'a'); window(c, 60, y, 'a')
gate(c, 55, 94, 11, 15, 'z')                                # ворота
# кристаллы у подножия: земля (оливковый) и воздух (сиреневый)
crystal(c, 34, 42, 56, 66, 5, 'H', 'j')
crystal(c, 78, 42, 56, 66, 5, 'A', 'a')
# парящие камни над стенами
for cx, cy in ((33, 30), (79, 33)):
    c.ellipse(cx, cy, 5, 2.6, 'e'); c.ellipse(cx, cy + 1.2, 4.5, 1.5, 'E')
conflux = finish(c)

# =====================================================================================
# Бухта: слева в зелёной воде корабль с белым парусом у пирса, по центру песчаный донжон
# с морской бирюзовой отделкой и тёплыми окнами, справа полосатый маяк с фонарём.
# =====================================================================================
c = Canvas(W, H)
rect(c, 0, 86, 37, 95, 'C')                                 # вода
rect(c, 0, 94, 37, 95, 'Q')                                 # глубина у дна
rect(c, 38, 95, 109, 95, 'T')                               # берег-фундамент
# корабль: тёмный корпус, светлая полоса, мачта, два паруса
c.poly([(1, 72), (35, 72), (31, 86), (5, 86)], 'N')
rect(c, 1, 72, 35, 74, 'n')
rect(c, 17, 30, 19, 71, 'N')                                # мачта
c.poly([(20, 33), (20, 68), (34, 68)], 'L')                 # большой парус
c.poly([(16, 40), (16, 68), (5, 68)], 'l')                  # малый парус
rect(c, 20, 60, 33, 68, 'l')                                # тень по низу большого паруса
# пирс на сваях от стены к воде
rect(c, 24, 80, 46, 83, 'n')
for x in (26, 34, 42): rect(c, x, 84, x + 2, 94, 'N')
# крепостная стена
rect(c, 38, 62, 84, 94, 'n')                                # бревенчатая стена
crenels(c, 40, 84, 61, 'n', w=5, gap=5, h=4)
for x in range(40, 84, 10): rect(c, x, 66, x + 2, 94, 'N')   # тёмные столбы частокола
# левая башня с бирюзовой конической крышей
tower(c, 36, 47, 48, 94, 'S', 'T', sw=3)
cone(c, 34, 49, 47, 34, 'C', 'Q')
# главная песчаная башня: плоский верх на 22
tower(c, 44, 70, 25, 94, 't', 'T', sw=5)
rect(c, 42, 22, 72, 25, 'T')                                # карниз-площадка
rect(c, 42, 44, 72, 47, 'C')                                # бирюзовый пояс
for y in (30, 52, 68):                                       # тёплые окна
    window(c, 50, y, 'y'); window(c, 61, y, 'y')
gate(c, 57, 94, 11, 15, 'D')                                # ворота
# маяк: белый, красные полосы, тёмная галерея, фонарь
c.poly([(90, 14), (102, 14), (106, 94), (86, 94)], 'w')
c.poly([(97, 14), (102, 14), (106, 94), (97, 94)], 'l')
for y in (28, 50, 72): rect(c, 86, y, 106, y + 5, 'r')
rect(c, 86, 12, 106, 15, 'E')                               # галерея
rect(c, 91, 4, 101, 11, 'y')                                # фонарь
rect(c, 89, 2, 103, 4, 'E')                                 # крыша фонаря
rect(c, 94, 6, 98, 9, 'w')                                  # огонь
cove = finish(c)

# =====================================================================================
# Фабрика: латунный центральный корпус с большой шестернёй и тёмными окнами, по бокам цеха
# из тёмного кирпича под медными крышами, из них графитовые трубы с дымом, медные трубопроводы.
