# ---------- формат вывода (как в castle_hd.block, без побочной пересборки чужих файлов) ----------
def pad(rows, W):
    return [(r + '.' * W)[:W] for r in rows]

def block(name, rows, comment, unit=2, paint=None, anchor=None):
    W = max(len(r) for r in rows); rows = pad(rows, W)
    body = '\n'.join("        '%s'," % r for r in rows)
    pt = (' paint: { ' + ', '.join('%s: %s' % (k, v) for k, v in paint.items()) + ' },') if paint else ''
    if anchor: pt += ' anchor: [%d, %d],' % tuple(anchor)   # якорь в ИСХОДНЫХ пикселях сетки (движок делит на unit)
    return "    /* %s (%d×%d) */\n    %s: {\n      hd: true, unit: %d,%s\n      rows: [\n%s\n      ],\n    },\n" % (comment, W, len(rows), name, unit, pt, body)


# ---------- примитивы ----------
def rect(c, x0, y0, x1, y1, mat):
    """прямоугольник: столбцы x0..x1-1, строки y0..y1-1 (полуоткрытый, как срезы)"""
    c.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], mat)

def tower(c, x0, x1, y0, y1, face, shade, sw=None, light=None, lw=3):
    """башня-призма: тело face, правая грань темнее (shade, ширина sw), слева световой столбец light (lw)"""
    rect(c, x0, y0, x1, y1, face)
    sw = sw or max(3, (x1 - x0) // 5)
    rect(c, x1 - sw, y0, x1, y1, shade)
    if light: rect(c, x0, y0, x0 + lw, y1, light)

def cone(c, cx, peak, base, half, light, mid, dark):
    """коническая крыша: вершина (плоская, 2 px) на строке peak, основание на base; левая грань light, правая dark"""
    c.poly([(cx - 1, peak), (cx + 1, peak), (cx + half, base), (cx - half, base)], mid)
    c.poly([(cx - 1, peak), (cx - half * 0.45, base), (cx - half, base)], light)
    c.poly([(cx + 1, peak), (cx + half, base), (cx + half * 0.45, base)], dark)

def gable(c, x0, x1, peak_x, peak_y, base_y, light, dark, ridge=2):
    """двускатная крыша анфас: левый скат light, правый dark; конёк плоский шириной ridge"""
    c.poly([(peak_x - ridge / 2, peak_y), (peak_x + ridge / 2, peak_y), (x1, base_y), (x0, base_y)], light)
    c.poly([(peak_x + ridge / 2, peak_y), (x1, base_y), (peak_x + ridge / 2, base_y)], dark)

def window(c, x, y, mat, w=4, h=6, top=None):
    rect(c, x, y, x + w, y + h, mat)
    if top: rect(c, x, y, x + w, y + 2, top)

def crenels(c, x0, x1, ybot, mat, w=6, gap=4, h=5):
    x = x0
    while x + w <= x1:
        rect(c, x, ybot - h, x + w, ybot, mat)
        x += w + gap

def arch(c, cx, ybot, w, h, mat):
    """арочный проём: прямоугольник + полукруг сверху; низ на строке ybot (не включая)"""
    r = w / 2.0
    rect(c, int(cx - r), int(ybot - h + r), int(cx + r), ybot, mat)
    c.ellipse(cx, ybot - h + r, r, r, mat)

def ground(c, x0, x1, ybot, top='d', bottom='D', h=4):
    """земляная подушка под объектом: верх top, нижняя строка bottom"""
    rect(c, x0, ybot - h, x1, ybot - 1, top)
    rect(c, x0, ybot - 1, x1, ybot, bottom)

def flame(c, cx, ybase, h, half, outer, core):
    c.poly([(cx - half, ybase), (cx + half, ybase), (cx + half * 0.3, ybase - h * 0.55), (cx + 1, ybase - h), (cx - 1, ybase - h), (cx - half * 0.3, ybase - h * 0.55)], outer)
    c.poly([(cx - half * 0.5, ybase), (cx + half * 0.5, ybase), (cx + 1, ybase - h * 0.5), (cx - 1, ybase - h * 0.5)], core)


def despeckle(rows):
    """одиночный пиксель (нет соседа своего тона по 4 сторонам) → тон самого частого соседа; пустота внутри — заливается"""
    g = [list(r) for r in rows]
    H, W = len(g), len(g[0])
    for _ in range(3):
        changed = 0
        for y in range(H):
            for x in range(W):
                col = g[y][x]
                nb = [g[y + dy][x + dx] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)) if 0 <= x + dx < W and 0 <= y + dy < H]
                if col == '.':
                    if len(nb) == 4 and all(n != '.' for n in nb): g[y][x] = max(set(nb), key=nb.count); changed += 1
                    continue
                if all(n != col for n in nb):
                    solid = [n for n in nb if n != '.']
                    g[y][x] = max(set(solid), key=solid.count) if len(solid) >= 2 else '.'; changed += 1
        if not changed: break
    return [''.join(r) for r in g]

def finish(c):
    return despeckle([r.replace('k', '.') for r in c.rows()])   # контурную линию не используем


