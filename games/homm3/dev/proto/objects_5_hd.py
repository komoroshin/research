WW, WH = 60, 88

def bricks(c, x0, x1, y0, y1, seed=1, bw=15, bh=10):
    """кладка: раствор E, блок e, блик l (5×3) в левом верхнем углу большинства блоков"""
    r = rnd(seed)
    rect(c, x0, y0, x1, y1, 'E')
    row = 0
    for y in range(y0, y1, bh):
        off = bw // 2 if row % 2 else 0
        x = x0 - off
        while x < x1:
            bx0, bx1 = max(x, x0), min(x + bw - 2, x1)
            by1 = min(y + bh - 2, y1)
            if bx1 - bx0 >= 4 and by1 - y >= 4:
                rect(c, bx0, y, bx1, by1, 'e')
                if r() < 0.7 and bx1 - bx0 >= 8: rect(c, bx0, y, bx0 + 5, y + 3, 'l')
                if r() < 0.25: rect(c, bx1 - 4, by1 - 3, bx1, by1, 'u')   # тёмный скол снизу справа
            x += bw
        row += 1

def merlon(c, x0, y0, y1, w=12, face='e'):
    """зубец: тело face, светлая верхняя площадка, правая грань в тени"""
    rect(c, x0, y0, x0 + w, y1, face)
    rect(c, x0, y0, x0 + w, y0 + 3, 'l')
    rect(c, x0 + w - 3, y0 + 3, x0 + w, y1, 'E')

def wall_base(c, seed=1):
    for x0 in (4, 24, 44): merlon(c, x0, 0, 14)
    rect(c, 0, 14, WW, 18, 'l')          # карниз (светлая плита)
    rect(c, 0, 18, WW, 21, 'E')          # тень под карнизом
    bricks(c, 0, WW, 21, 84, seed)
    rect(c, 0, 84, WW, WH, 'u')          # цоколь в тени

def crack(c, pts, th=2):
    """трещина: ломаная тёмно-синим z с графитовой каймой u"""
    for i in range(len(pts) - 1):
        thick(c, pts[i][0], pts[i][1], pts[i + 1][0], pts[i + 1][1], th + 2, 'u')
    for i in range(len(pts) - 1):
        thick(c, pts[i][0], pts[i][1], pts[i + 1][0], pts[i + 1][1], th, 'z')

