# ---------- примитивы ----------
def rect(c, x0, y0, x1, y1, m):
    """столбцы x0..x1-1, строки y0..y1-1 (полуоткрытый, как срезы)"""
    c.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], m)

def hline(c, x0, x1, y, th, m): rect(c, x0, y, x1, y + th, m)
def vline(c, x, y0, y1, th, m): rect(c, x, y0, x + th, y1, m)

def thick(c, x0, y0, x1, y1, th, m):
    """толстая линия как полоса-многоугольник (ровные края, без дырок)"""
    dx, dy = x1 - x0, y1 - y0; L = math.hypot(dx, dy) or 1
    nx, ny = -dy / L * th / 2, dx / L * th / 2
    c.poly([(x0 + nx, y0 + ny), (x1 + nx, y1 + ny), (x1 - nx, y1 - ny), (x0 - nx, y0 - ny)], m)

def despeckle(c, passes=2):
    """одиночный пиксель (нет соседа того же цвета по 4-связности) → самый частый сосед;
    дырка-прозрачность внутри заливки → самый частый сосед"""
    for _ in range(passes):
        g2 = [row[:] for row in c.g]
        for y in range(c.h):
            for x in range(c.w):
                v = c.g[y][x]
                nb = [c.get(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]
                if v == '.':
                    if all(n != '.' for n in nb):
                        g2[y][x] = max(set(nb), key=nb.count)
                    continue
                if v not in nb:
                    cand = [n for n in nb if n != '.'] or nb
                    g2[y][x] = max(set(cand), key=cand.count)
        c.g = g2

def rows(c):
    despeckle(c)
    return c.rows()

def rnd(seed):
    """крошечный детерминированный генератор (чтобы кладка не была идеально ровной)"""
    s = [seed]
    def f():
        s[0] = (s[0] * 1103515245 + 12345) & 0x7fffffff
        return s[0] / 0x7fffffff
    return f

