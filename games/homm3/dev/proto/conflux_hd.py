def rect(c, x, y, w, h, mat):
    """прямоугольник x..x+w-1, y..y+h-1"""
    c.poly([(x, y), (x + w, y), (x + w, y + h), (x, y + h)], mat)

def despeckle(rows):
    """убираем «рябь»: пиксель без соседа своего тона (по 4 сторонам и по диагонали) красим в самый частый тон вокруг"""
    H, W = len(rows), len(rows[0])
    def get(x, y): return rows[y][x] if 0 <= x < W and 0 <= y < H else '.'
    out = [r[:] for r in rows]
    for y in range(H):
        for x in range(W):
            ch = rows[y][x]
            if ch == '.': continue
            around = [get(x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1) if dx or dy]
            if ch in around: continue
            solid = [a for a in around if a != '.']
            out[y][x] = max(set(solid), key=solid.count) if len(solid) >= 3 else '.'
    return out

def finish(c, pupils=()):
    """стиль Б: контур не нужен — прогоняем outline и стираем 'k', чистим рябь, потом возвращаем зрачки"""
    c.outline(between=set())
    rows = despeckle([list(r.replace('k', '.')) for r in c.rows()])
    for x, y in pupils: rows[y][x] = 'k'
    return [''.join(r) for r in rows]

def plus(x, y, mat):
    """крестик 3×3 (искра) — связная примета вместо одиночного пикселя"""
    return [(x, y, mat), (x - 1, y, mat), (x + 1, y, mat), (x, y - 1, mat), (x, y + 1, mat)]

