# ---------- примитивы ----------
def rect(c, x0, y0, x1, y1, mat):
    """прямоугольник: столбцы x0..x1-1, строки y0..y1-1 (полуоткрытый, как срезы)"""
    c.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], mat)

def tower(c, x0, x1, y0, y1, face, shade, sw=None, light=None, lw=3):
    """призма: тело face, правая грань темнее (shade, ширина sw), слева световой столбец light (lw)"""
    rect(c, x0, y0, x1, y1, face)
    sw = sw or max(3, (x1 - x0) // 5)
    rect(c, x1 - sw, y0, x1, y1, shade)
    if light: rect(c, x0, y0, x0 + lw, y1, light)

def cone(c, cx, peak, base, half, light, mid, dark, top=2):
    """коническая крыша: вершина (плоская, top px) на строке peak, основание на base; левая грань light, правая dark"""
    c.poly([(cx - top / 2, peak), (cx + top / 2, peak), (cx + half, base), (cx - half, base)], mid)
    c.poly([(cx - top / 2, peak), (cx - half * 0.45, base), (cx - half, base)], light)
    c.poly([(cx + top / 2, peak), (cx + half, base), (cx + half * 0.45, base)], dark)

def window(c, x, y, mat, w=6, h=8, top=None):
    """окно w×h; top — цвет верхних двух строк (свет арки)"""
    rect(c, x, y, x + w, y + h, mat)
    if top: rect(c, x, y, x + w, y + 2, top)

def arch(c, cx, ybot, w, h, mat):
    """арочный проём: прямоугольник + полукруг сверху; низ на строке ybot (не включая)"""
    r = w / 2.0
    rect(c, int(cx - r), int(ybot - h + r), int(cx + r), ybot, mat)
    c.ellipse(cx, ybot - h + r, r, r, mat)

def door(c, cx, ybot, w, h, frame, dark):
    """дверь: деревянная арка frame и тёмный проём dark внутри"""
    arch(c, cx, ybot, w, h, frame)
    arch(c, cx, ybot, w - 4, h - 3, dark)

def ground(c, W, H, x0, x1, mat, shade, h=4):
    """полоса земли под объектом: верх mat, нижняя строка shade"""
    rect(c, x0, H - h, x1, H - 1, mat); rect(c, x0, H - 1, x1, H, shade)

def finish(c, W, H, passes=2):
    """стиль Б: контура нет — убираем одиночные пиксели: висящие по краю (≤1 соседа) стираем,
    а пиксель, у которого нет соседа того же цвета, красим в самый частый цвет соседей"""
    rows = [list(r) for r in c.rows()]
    for _ in range(passes):
        def get(x, y): return rows[y][x] if 0 <= x < W and 0 <= y < H else '.'
        for y in range(H):
            for x in range(W):
                ch = rows[y][x]
                if ch == '.': continue
                nb = [get(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]
                filled = [n for n in nb if n != '.']
                if len(filled) <= 1: rows[y][x] = '.'; continue
                if ch not in filled:
                    rows[y][x] = max(set(filled), key=filled.count)
    return [''.join(r) for r in rows]

SPR = []   # (имя, rows, комментарий)
def add(name, c, W, H, comment):
    rows = finish(c, W, H)
    assert len(rows) == H and all(len(r) == W for r in rows), name
    SPR.append((name, rows, comment))

