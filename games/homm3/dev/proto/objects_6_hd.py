# ---------- примитивы ----------
def rect(c, x0, y0, x1, y1, mat):
    """прямоугольник: столбцы x0..x1-1, строки y0..y1-1 (полуоткрытый, как срезы)"""
    c.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], mat)

def wall(c, x0, x1, y0, y1, sw=None, face='n', shade='N'):
    """стена-призма: тело face, правая грань темнее (shade) шириной sw"""
    rect(c, x0, y0, x1, y1, face)
    sw = sw if sw is not None else max(3, (x1 - x0) // 8)
    rect(c, x1 - sw, y0, x1, y1, shade)

def gable(c, x0, x1, peak, base, over=4, light='r', dark='R', cx=None):
    """двускатная крыша фасадом: трапеция от конька (плоский, 4 px) до основания base, свесы over;
    правый скат темнее, под свесом двухстрочная тень"""
    cx = cx if cx is not None else (x0 + x1) / 2.0
    L, Rr = x0 - over, x1 + over
    c.poly([(cx - 2, peak), (cx + 2, peak), (Rr, base), (L, base)], light)
    c.poly([(cx + 2, peak), (Rr, base), (cx + (Rr - cx) * 0.5, base)], dark)
    rect(c, L, base - 2, Rr, base, dark)

def cone(c, cx, peak, base, half, light='r', dark='R'):
    """коническая крыша башни: плоская вершина 4 px, правая грань темнее"""
    c.poly([(cx - 2, peak), (cx + 2, peak), (cx + half, base), (cx - half, base)], light)
    c.poly([(cx + 2, peak), (cx + half, base), (cx + half * 0.45, base)], dark)
    rect(c, cx - half, base - 2, cx + half, base, dark)

def crenels(c, x0, x1, ybot, w=6, gap=4, h=6, mat='n', shade='N'):
    """зубцы: от x0 шагом w+gap, высота h, нижняя строка ybot (стена ниже); под ними — тень боевого хода"""
    x = x0
    while x + w <= x1:
        rect(c, x, ybot - h, x + w, ybot, mat)
        x += w + gap
    rect(c, x0, ybot, x1, ybot + 3, shade)

def window(c, x, y, w=6, h=8, mat='y', sill='N', arch=False):
    """окно w×h, под ним подоконник; arch — арочный верх"""
    rect(c, x, y, x + w, y + h, mat)
    if arch: c.ellipse(x + w / 2.0, y, w / 2.0, w / 2.0, mat)
    if sill: rect(c, x - 1, y + h, x + w + 1, y + h + 2, sill)

def arch(c, cx, ybot, w, h, mat):
    """арочный проём: прямоугольник + полукруг сверху; низ на строке ybot (не включая)"""
    r = w / 2.0
    rect(c, int(cx - r), int(ybot - h + r), int(cx + r), ybot, mat)
    c.ellipse(cx, ybot - h + r, r, r, mat)

def door(c, cx, ybot, w=10, h=16, frame='N', inner='D'):
    """дверь: тёмная арка в раме"""
    arch(c, cx, ybot, w + 4, h + 2, frame)
    arch(c, cx, ybot, w, h, inner)

def chimney(c, x0, x1, ytop, ybot):
    """каменная труба: серая, правая грань темнее, светлый венец"""
    rect(c, x0, ytop, x1, ybot, 'e'); rect(c, x1 - 2, ytop, x1, ybot, 'E')
    rect(c, x0 - 1, ytop, x1 + 1, ytop + 3, 'l')

def portcullis(c, cx, ybot, w, h):
    """решётка ворот: каменная арка, тёмный проём, светлые прутья"""
    arch(c, cx, ybot, w + 6, h + 3, 'E')
    arch(c, cx, ybot, w, h, 'z')
    x = int(cx - w / 2.0) + 3
    while x < cx + w / 2.0 - 2:
        rect(c, x, ybot - h + 4, x + 2, ybot, 'l'); x += 5
    for y in range(ybot - h + 8, ybot, 7): rect(c, int(cx - w / 2.0) + 1, y, int(cx + w / 2.0) - 1, y + 2, 'l')

def orb(c, cx, cy, r):
    """магический шар гильдии: голубой с бликом, правая тень"""
    c.ellipse(cx, cy, r, r, 'b')
    c.poly([(cx + r * 0.3, cy - r), (cx + r + 1, cy - r * 0.3), (cx + r + 1, cy + r * 0.3), (cx + r * 0.3, cy + r + 1)], 'B')
    c.ellipse(cx - r * 0.3, cy - r * 0.2, r * 0.5, r * 0.6, 'c')
    c.ellipse(cx - r * 0.4, cy - r * 0.35, r * 0.22, r * 0.25, 'w')

def plinth(c, x0, x1, ybot):
    """цоколь: тёмный ряд стены и почти чёрная полоса земли"""
    rect(c, x0, ybot - 4, x1, ybot - 2, 'N'); rect(c, x0, ybot - 2, x1, ybot, 'D')

def despeckle(rows):
    """убираем «рябь»: пиксель без соседа своего тона (8 сторон) красим в самый частый тон вокруг"""
    H, W = len(rows), len(rows[0])
    def get(x, y): return rows[y][x] if 0 <= x < W and 0 <= y < H else '.'
    out = [r[:] for r in rows]
    for y in range(H):
        for x in range(W):
            ch = rows[y][x]
            if ch == '.': continue
            around = [get(x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1) if dx or dy]
            if ch in around: continue
            solid = [a for a in around if a != '.']
            out[y][x] = max(set(solid), key=solid.count) if len(solid) >= 3 else '.'
    return out

def finish(c):
    """стиль Б: контура нет — стираем 'k', чистим рябь"""
    return [''.join(r) for r in despeckle([list(r.replace('k', '.')) for r in c.rows()])]

OUT = []
def add(name, c, comment):
    OUT.append(block(name, finish(c), comment))

