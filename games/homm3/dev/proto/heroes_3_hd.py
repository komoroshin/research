def block(name, rows, comment, unit=2):
    """как castle_hd.block, но без импорта castle_hd (чтобы не пересобирать чужой файл)"""
    W = max(len(r) for r in rows); rows = [(r + '.' * W)[:W] for r in rows]
    body = '\n'.join("        '%s'," % r for r in rows)
    return "    /* %s (%d×%d) */\n    %s: {\n      hd: true, unit: %d,\n      rows: [\n%s\n      ],\n    },\n" % (comment, W, len(rows), name, unit, body)

W, H = 48, 52

def despeckle(rows):
    """одиночные пиксели убираем: точка без соседа того же цвета по четырём сторонам красится в самый частый соседний цвет"""
    g = [list(r) for r in rows]
    h, w = len(g), len(g[0])
    for y in range(h):
        for x in range(w):
            c = g[y][x]
            if c == '.': continue
            nb = [g[y + dy][x + dx] for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)) if 0 <= x + dx < w and 0 <= y + dy < h]
            if c in nb: continue
            fill = [n for n in nb if n != '.']
            g[y][x] = max(set(fill), key=fill.count) if fill else '.'
    return [''.join(r) for r in g]

def finish(c, eyes):
    """контур не нужен (стиль Б): outline → снять k → despeckle → точечно k для глаз"""
    c.outline(between=set())
    rows = despeckle([r.replace('k', '.') for r in c.rows()])
    g = [list(r) for r in rows]
    for x, y in eyes: g[y][x] = 'k'
    return [''.join(r) for r in g]

# ---------- конь в профиль: тело ellipse, шея poly, голова ellipse, четыре ноги poly (дальние темнее), хвост, грива ----------
def legs(c, pairs, hoof):
    for x0, dx, mat in pairs:
        c.poly([(x0, 36), (x0 + dx, 50), (x0 + dx + 5, 50), (x0 + 5, 36)], mat)
        c.poly([(x0 + dx - 1, 49), (x0 + dx + 6, 49), (x0 + dx + 6, 52), (x0 + dx - 1, 52)], hoof)   # копыто на нижней строке

def horse(c, body, shade, light, mane, hoof, halo=None, harness=None):
    legs(c, ((13, -2, shade), (32, 3, shade)), hoof)                                   # дальние ноги
    c.poly([(11, 28), (4, 34), (2, 45), (6, 46), (9, 37), (14, 33)], mane)             # хвост
    c.ellipse(25, 33, 15, 7.5, body); c.ellipse(14, 31, 7, 6, body); c.ellipse(37, 30, 6, 6, body)   # тело, круп, грудь
    c.ellipse(24, 29, 11, 3, light)                                                     # свет по спине
    c.ellipse(25, 37, 12, 3.5, shade)                                                   # брюхо
    if halo: c.ellipse(42, 11, 8, 7, halo)                                               # ореол вокруг головы (Сопряжение)
    c.poly([(31, 28), (37, 10), (46, 12), (43, 31)], body)                             # шея (шире)
    c.ellipse(43, 12, 5, 4.5, body); c.ellipse(46.5, 14.5, 2.5, 2.2, shade)            # голова крупнее и морда
    c.poly([(39, 6), (40, 10), (42, 10)], body); c.poly([(43, 6), (43, 10), (45, 10)], body)   # уши
    c.feathers([(39, 8), (33, 27)], mane, 2.0, (-0.6, -0.2))                            # грива по загривку
    legs(c, ((19, 1, body), (37, -1, body)), hoof)                                      # ближние ноги
    if harness:                                                                          # сбруя: нагрудный ремень, подпруга, нащёчный ремень
        c.line(34, 26, 40, 35, harness, th=2)
        c.poly([(33, 27), (37, 27), (37, 40), (33, 40)], harness)
        c.line(39, 9, 45, 15, harness, th=2)

def saddle(c, y=31):
    """попона — только b (свет) и B (тень); видна спереди и сзади из-под всадника"""
    c.ellipse(24, y, 9.5, 5.5, 'b')
    c.ellipse(24, y + 3.5, 8.5, 2.5, 'B')

def torso(c, coat, leg, boot, top=13):
    c.poly([(18, top), (29, top), (30, 27), (17, 27)], coat)     # торс
    c.poly([(21, 25), (28, 25), (26, 40), (20, 40)], leg)         # ближняя нога поверх попоны
    c.poly([(19, 39), (27, 39), (28, 44), (19, 44)], boot)        # сапог

def reins(c, col='D'): c.line(33, 19, 45, 15, col, th=1)

