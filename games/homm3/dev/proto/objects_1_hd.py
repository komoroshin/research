# ---------- примитивы ----------
def rect(c, x0, y0, x1, y1, mat):
    """прямоугольник: столбцы x0..x1-1, строки y0..y1-1"""
    c.poly([(x0, y0), (x1, y0), (x1, y1), (x0, y1)], mat)

def mound(c, cx, top, base, half, light, mid, dark, ledge=None):
    """холм-полуэллипс: основание на строке base (не включая), вершина top; правая часть темнее, левый бок светлее"""
    ry = base - top
    c.ellipse(cx, base, half, ry, dark)
    c.ellipse(cx - half * 0.12, base, half * 0.82, ry * 0.97, mid)
    c.ellipse(cx - half * 0.35, base, half * 0.42, ry * 0.86, light)
    rect(c, 0, base, c.w, c.h, '.')   # ниже основания — чисто

def entrance(c, cx, ybot, w, h, frame='N', post='n', hole='z'):
    """вход в шахту: деревянная рама (стойки post, перекладина frame), тёмный проём hole"""
    rect(c, int(cx - w / 2), ybot - h, int(cx + w / 2), ybot, frame)
    rect(c, int(cx - w / 2) + 2, ybot - h + 3, int(cx + w / 2) - 2, ybot, hole)
    rect(c, int(cx - w / 2), ybot - h + 3, int(cx - w / 2) + 3, ybot, post)
    rect(c, int(cx + w / 2) - 3, ybot - h + 3, int(cx + w / 2), ybot, post)

def ground(c, x0, x1, mat='d', dark='D'):
    """полоска земли под объектом: три строки mat и одна dark в самом низу"""
    rect(c, x0, c.h - 4, x1, c.h - 1, mat); rect(c, x0 + 2, c.h - 1, x1 - 2, c.h, dark)

def crystal(c, xb0, xb1, ybase, xt, ytop, light, mid, dark):
    """кристалл-шип: основание xb0..xb1 на строке ybase, остриё (2 px) у (xt, ytop); левая грань light, правая dark"""
    mx = (xb0 + xb1) / 2.0
    c.poly([(xb0, ybase), (xb1, ybase), (xt + 1, ytop), (xt - 1, ytop)], mid)
    c.poly([(xb0, ybase), (mx - (mx - xb0) * 0.25, ybase), (xt - 1, ytop)], light)
    c.poly([(xb1, ybase), (mx + (xb1 - mx) * 0.3, ybase), (xt + 1, ytop)], dark)

def log_end(c, cx, cy, r, ring='n', core='T', rim='N'):
    """торец бревна: тёмное кольцо, кольцо коричневое, светлая сердцевина"""
    c.ellipse(cx, cy, r, r, rim); c.ellipse(cx, cy, r - 1, r - 1, ring); c.ellipse(cx, cy, r * 0.5, r * 0.5, core)

def flame(c, cx, ybase, h, half, outer, mid, core):
    """язык пламени: три вложенных языка — outer, mid, core"""
    c.poly([(cx - half, ybase), (cx + half, ybase), (cx + half * 0.35, ybase - h * 0.55), (cx + 1, ybase - h), (cx - 1, ybase - h), (cx - half * 0.35, ybase - h * 0.55)], outer)
    c.poly([(cx - half * 0.62, ybase), (cx + half * 0.62, ybase), (cx + half * 0.2, ybase - h * 0.45), (cx + 1, ybase - h * 0.7), (cx - 1, ybase - h * 0.7), (cx - half * 0.2, ybase - h * 0.45)], mid)
    c.poly([(cx - half * 0.3, ybase), (cx + half * 0.3, ybase), (cx + 1, ybase - h * 0.38), (cx - 1, ybase - h * 0.38)], core)

def sparkle(c, cx, cy, mat, r=2):
    """искра-звёздочка: крестик с плечами r"""
    rect(c, cx - r, cy, cx + r + 1, cy + 1, mat); rect(c, cx, cy - r, cx + 1, cy + r + 1, mat)

def despeckle(rows):
    """убираем «рябь»: пиксель без соседа своего тона (8 соседей) красим в самый частый тон вокруг"""
    H, W = len(rows), len(rows[0])
    def get(x, y): return rows[y][x] if 0 <= x < W and 0 <= y < H else '.'
    out = [r[:] for r in rows]
    for y in range(H):
        for x in range(W):
            ch = rows[y][x]
            if ch == '.': continue
            around = [get(x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1) if dx or dy]
            if ch in around: continue
            solid = [a for a in around if a != '.']
            out[y][x] = max(set(solid), key=solid.count) if len(solid) >= 3 else '.'
    return out

def finish(c, keep_k=()):
    """стиль Б: контур не рисуем, 'k' стираем (кроме точек keep_k), чистим рябь"""
    rows = despeckle([list(r.replace('k', '.')) for r in c.rows()])
    for x, y in keep_k: rows[y][x] = 'k'
    return [''.join(r) for r in rows]

