/* Проверка дека: числа и плотность.

   ТЗ версии 3 задаёт два теста вместо одного.

   Точность: можно ли назвать источник каждого числа в одном предложении?
   Машина проверяет то, что проверяется машиной, — сходятся ли числа между
   собой и не осталось ли формулировок, запрещённых в этой версии.

   Плотность: можно ли пересказать слайд одним предложением человеку, который
   видит его пять секунд? Здесь машина считает объём текста на слайде и
   ищет таблицы и сноски там, где их быть не должно.

   Запуск: node check-numbers.mjs
   Ненулевой код — если сломалась связка или всплыла запрещённая строка.
   Расхождения, которые нельзя решить без финмодели, печатаются отдельным
   блоком «требует решения» и код возврата не меняют. */

import { readFileSync } from 'node:fs'

const src = readFileSync(new URL('./content.js', import.meta.url), 'utf8')
const parsed = src
  .split(/^===[ \t]*/m)
  .slice(1)
  .map((chunk) => {
    const [head, ...rest] = chunk.split('\n')
    const opts = head.split('|').map((x) => x.trim())
    const [kind, num] = opts[0].split(/\s+/)
    const body = rest.join('\n').split(/^---[ \t]*notes[ \t]*$/m)[0]
    return { kind, num: Number(num), internal: opts.includes('internal'), body }
  })
const slides = Object.fromEntries(parsed.map((s) => [`${s.kind} ${s.num}`, s.body]))
const main = parsed.filter((s) => s.kind === 'slide').sort((a, b) => a.num - b.num)
const deck = src

let failed = 0
const ok = (label, pass, detail) => {
  console.log(`${pass ? '  ok  ' : ' FAIL '} ${label}${detail ? ': ' + detail : ''}`)
  if (!pass) failed++
}
const near = (a, b, eps = 1) => Math.abs(a - b) <= eps

console.log('Точность — связки внутри финансовой части\n')

// Слайд 9: валовая маржа считается до резерва на возвраты, вклад — после.
const gross = (179 - 12) / 179
ok('93% валовой маржи = ($179 − $12) / $179', near(gross * 100, 93, 0.5),
   `${(gross * 100).toFixed(1)}% против заявленных 93%`)
const contribution = 179 - 11.89 - 179 * 0.07
ok('вклад $155 = $179 − $11,89 − 7% на возвраты', near(contribution, 155, 1),
   `$${contribution.toFixed(2)} против заявленных $155`)

// Потолок привлечения: отраслевое требование LTV/CAC не ниже трёх.
ok('$75 ≈ нижняя граница потолка: $188 / 3 = $63, округлено вверх до порога',
   near(188 / 3, 63, 1))
ok('$150 не выше пожизненной ценности нижнего сценария', 150 < 188)

// Слайд 9: три крупных числа повторяют то, что стоит в буллетах.
const s9 = slides['slide 9'] || ''
for (const n of ['$155', '$188–249', '$150']) {
  ok(`на слайде 9 крупно стоит ${n}`, s9.includes(`[big] ${n}`))
}
ok('заголовок слайда 9 повторяет $179 и $155',
   /\$179/.test(s9.split('\n')[0]) && /\$155/.test(s9.split('\n')[0]))

// Один и тот же коридор привлечения на слайдах 9, 11 и 14.
const s11 = slides['slide 11'] || ''
const s14 = slides['slide 14'] || ''
ok('коридор $75–150 назван на слайдах 11 и 14',
   /\$75–150/.test(s11) && /\$75–150/.test(s14))
ok('слайд 9 называет обе границы того же коридора',
   /\$150/.test(s9) && /\$75/.test(s9))

// Ask: сумма заголовка = сумма двух этапов.
const stages = [...s14.matchAll(/\$(\d[\d\s]*\d)\b/g)].map((m) => Number(m[1].replace(/\s/g, '')))
const ask = /\$(\d+)k/.exec(s14.split('\n')[0])
ok('заголовок ask = этап 1 + этап 2',
   ask && stages.includes(25000) && stages.includes(140000) && Number(ask[1]) * 1000 === 165000,
   `$25 000 + $140 000 = $165 000, в заголовке $${ask ? ask[1] : '?'}k`)

// Завершаемость переехала на слайд 3 и осталась при своём источнике.
const s3 = slides['slide 3'] || ''
ok('слайд 3 называет 41% и источник', /41%/.test(s3) && /UCLH, 233 пациента/.test(s3))
ok('слайд 3 оговаривает, что это не отраслевая константа', /Не отраслевая константа/.test(s3))
ok('те же 233 пациента стоят за цифрами РПП на слайде 12',
   /23%/.test(slides['slide 12'] || '') && /57% против 35%/.test(slides['slide 12'] || ''))

// Горизонт: три года подряд, первый — тот, что строится сейчас.
const s7 = slides['slide 7'] || ''
const years = [...s7.matchAll(/^\[time\] (Год \d)/gm)].map((m) => m[1])
ok('на слайде видения три года подряд', years.join(' → ') === 'Год 1 → Год 2 → Год 3', years.join(' → '))
ok('первый год — тот протокол, что строится сейчас', /\[time\] Год 1 \| СРК/.test(s7))

console.log('\nСметы этапов (приложение, internal)\n')

const money = (chunk) =>
  [...chunk.matchAll(/^\|\s*(?:\*\*)?([^|*]+?)(?:\*\*)?\s*\|\s*(?:\*\*)?~?([\d\s]+?)(?:\*\*)?\s*\|$/gm)]
    .map((m) => ({ name: m[1].trim(), v: Number(m[2].replace(/\s/g, '')) }))
    .filter((r) => Number.isFinite(r.v) && r.v > 0)

const a4 = money(slides['appendix 4'] || '')
const a4items = a4.filter((r) => r.name !== 'Итого')
const a4total = a4.find((r) => r.name === 'Итого')
ok('смета смоук-теста сходится к итогу',
   a4total && a4items.reduce((n, r) => n + r.v, 0) === a4total.v,
   `${a4items.reduce((n, r) => n + r.v, 0)} против ${a4total ? a4total.v : '—'}`)
ok('итог сметы смоук-теста = цена этапа 1', a4total && a4total.v === 25000)

const a9 = money(slides['appendix 9'] || '')
const cost = a9.find((r) => r.name === 'Сырая себестоимость')
const markup = a9.find((r) => r.name === 'Наценка за перенесённую ценность')
const price = a9.find((r) => r.name === 'Фиксированная цена')
const a9items = a9.filter((r) => ![cost, markup, price].includes(r))
ok('сырая себестоимость MVP = сумма своих строк',
   cost && a9items.reduce((n, r) => n + r.v, 0) === cost.v,
   `${a9items.reduce((n, r) => n + r.v, 0)} против ${cost ? cost.v : '—'}`)
ok('себестоимость + наценка = фиксированная цена',
   cost && markup && price && cost.v + markup.v === price.v,
   cost && markup && price ? `${cost.v} + ${markup.v} = ${cost.v + markup.v}, заявлено ${price.v}` : '')
ok('цена MVP из сметы = цена этапа 2', price && price.v === 140000)

// Пороги и капитал переехали в приложение, но остались теми же.
const a10 = slides['appendix 10'] || ''
const a11 = slides['appendix 11'] || ''
for (const t of ['ниже $75', '$75–150', 'выше $150']) {
  ok(`порог «${t}» есть в приложении`, a10.includes(t))
}
const rows = [...a11.matchAll(/\|\s*([^|]+?)\s*\|\s*\$(\d+)k\s*\|\s*\$(\d+)k\s*\|/g)].map((m) => ({
  low: Number(m[2]), high: Number(m[3]),
}))
ok('в таблице капитала три рубежа', rows.length === 3, `найдено ${rows.length}`)
ok('колонка «при CAC $75» одинакова по всем рубежам',
   rows.length === 3 && new Set(rows.map((r) => r.low)).size === 1)
ok('колонка «при CAC $150» растёт от рубежа к рубежу',
   rows.length === 3 && rows[0].high < rows[1].high && rows[1].high < rows[2].high,
   rows.map((r) => '$' + r.high + 'k').join(' → '))

const internalCount = parsed.filter((s) => s.internal).length
ok('backup-слайды помечены internal', internalCount === 5, `помечено ${internalCount} из 5`)

console.log('\nПлотность — что видно за пять секунд\n')

// Порог подобран по деку: тезисные слайды версии 1 держатся в пределах 400
// знаков, самый тяжёлый слайд версии 3 — видение, и он тяжёлый вынужденно:
// дельта добавила туда пятый пункт и сноску про телемедицину. Порог стоит
// выше него ровно настолько, чтобы поймать следующий такой прирост.
const LIMIT = 900
// Служебные строки ([big], [time], [img]) отбрасываются построчно. Раньше
// они вычищались регуляркой уже после склейки — и `[^\n]*` съедал весь
// остаток слайда, из-за чего слайд с таймлайном считался лёгким.
const weight = (s) =>
  s.body
    .split('\n')
    .map((l) => l.trim())
    .filter((l) => l && !l.startsWith('# ') && !/^\[(big|time|img)\]/.test(l))
    .join(' ').length
const ranked = main.map((s) => ({ n: s.num, w: weight(s) })).sort((a, b) => b.w - a.w)
const heavy = ranked.filter((s) => s.w > LIMIT)
ok(`ни один слайд не тяжелее ${LIMIT} знаков`, heavy.length === 0,
   heavy.map((s) => `${s.n} — ${s.w}`).join(', ') ||
     'самые плотные: ' + ranked.slice(0, 3).map((s) => `слайд ${s.n} — ${s.w}`).join(', '))

// Таблица на слайде допустима там, где она и есть содержание слайда.
const withTables = main.filter((s) => /^\|/m.test(s.body)).map((s) => s.num)
ok('таблицы только на конкурентной карте и рисках',
   withTables.join(',') === '10,12', withTables.join(', ') || 'нет')

// Сноска — хеджирование. Разрешены две: источник цифры завершаемости на
// слайде 3 и оговорка про права на телемедицинский модуль на слайде 7.
const withNotes = main.filter((s) => /^> /m.test(s.body)).map((s) => s.num)
ok('сноски только на слайдах 3 и 7', withNotes.join(',') === '3,7', withNotes.join(', ') || 'нет')

console.log('\nЗапрещено в этой версии\n')
const banned = [
  [/20\s?000/, 'график и строка с 20 000 пользователей'],
  [/\$3,5 млн/, 'строка «20 000 × $179 ≈ $3,5 млн»'],
  [/транш/i, 'транши — сделки с ними больше нет'],
  [/раунд/i, 'слово «раунд»'],
  [/вестинг|опцион|доля в проекте/i, 'условия по доле'],
  [/0,5%/, 'порог по конверсии'],
  [/Права — у проекта/i, 'утверждение о правах на движок'],
]
for (const [re, label] of banned) {
  ok(`нет: ${label}`, !re.test(deck), re.test(deck) ? deck.match(re)[0] : '')
}
// Цена подписки на слайде создала бы противоречие с опубликованным лендингом.
const subPrice = main.some((s) => /\$\d+\/мес/.test(s.body) && s.num !== 10)
ok('дек не называет цену подписки — противоречить лендингу нечем', !subPrice)

console.log('\nТребует решения — машина проверить не может\n')
const open = []

if (/93% валовой маржи/.test(s9) && /\$155/.test(s9)) {
  open.push(
    'Слайд 9. На одном слайде две разные маржи: валовая 93% — это $179 − $12 = $167, ' +
      'а $155 — вклад после резерва на возвраты 7%. Кто разделит 155 на 179, получит 87% ' +
      'и спросит про третье число. Либо назвать обе явно, либо оставить одну.'
  )
}

if (/Программа — \$179/.test(slides['slide 8'] || '') && /Следующий протокол — снова программа, \$149/.test(slides['slide 8'] || '')) {
  open.push(
    'Слайд 8. Первая программа стоит $179, следующая — $149, и это цена ' +
      'годового плана поддержания. Так в ТЗ. Если это цена возврата, стоит ' +
      'сказать почему; если опечатка — поправить одну строку.'
  )
}

if (/Около 30% берут второй/.test(s7)) {
  open.push(
    'Слайд 7. «Около 30% берут второй протокол» — это допущение финансовой модели, ' +
      'а не измеренная величина, и на слайде оно выглядит как факт. На самом слайде ' +
      'оговорки нет намеренно (правило плотности), в заметках она есть — но если ' +
      'комитет спросит источник, ответ должен звучать одинаково у всех.'
  )
}

// Слайд видения после дельты вдвое тяжелее следующего за ним — формально в
// пределах порога, по сути мимо теста «пять секунд».
if (ranked[0].w > ranked[1].w * 1.3) {
  open.push(
    `Плотность. Слайд ${ranked[0].n} — ${ranked[0].w} знаков, следующий за ним ` +
      `слайд ${ranked[1].n} — ${ranked[1].w}. Разрыв в полтора раза: пять пунктов ` +
      `и сноска на одном слайде тест «пересказать за пять секунд» не проходят, ` +
      `сколько бы вёрстка их ни ужимала. Что режется без потери смысла: сноска про ` +
      `права уезжает в заметки — сам пункт уже говорит «вне объёма текущего этапа», ` +
      `а «предмет отдельного разговора» комитету на слайде не нужно.`
  )
}

const s6 = slides['slide 6'] || ''
if (/FHIR/.test(s6) && /распознавание выписок/.test(s6)) {
  open.push(
    'Слайд 6. Список наработок идёт под одной оговоркой, а риск владения внутри ' +
      'него разный: Apple Health, Google Health и FHIR — публичные API и открытый ' +
      'стандарт, а распознавание выписок и корреляционный движок по риску ближе к ' +
      'протокольному ядру. На слайде это разделять не надо, но юрист должен ' +
      'получить список уже разделённым.'
  )
}

const s7d = slides['slide 7'] || ''
if (/инфраструктура для подбора врача/.test(s7d)) {
  open.push(
    'Слайд 7. Строка про телемедицину — про существование модуля, не про права ' +
      'на него: он написан членом команды вне контракта с клиникой, но юристом это ' +
      'не подтверждено. Сноска под слайдом закрывает вопрос ровно настолько, ' +
      'насколько можно. Со сцены «права чище» не произносить.'
  )
}

if (/\$165–280/.test(slides['appendix 4'] || '')) {
  open.push(
    'Приложение 4. Смета обещает, что при трафике $12k интервал по CAC сужается ' +
      'до $165–280, а порог режет по $75 и $150 — такой интервал не разделяет ни ' +
      'одну из границ. Либо это интервал вокруг конкретной точечной оценки и это ' +
      'надо сказать прямо, либо трафика мало для объявленного порога.'
  )
}

if (open.length === 0) console.log('  — нечего')
for (const line of open) console.log('  ?  ' + line + '\n')

console.log(failed ? `\nСломано связок: ${failed}` : '\nВсе машинно проверяемые связки сходятся.')
process.exit(failed ? 1 : 0)
