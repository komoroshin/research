/* Проверка чисел в деке.

   Требование ТЗ версии 2: каждое число должно проходить один тест — можно ли
   назвать его источник в одном предложении. Скрипт проверяет то, что можно
   проверить машиной: сходятся ли числа между собой и не осталось ли в файле
   формулировок, запрещённых в этой версии.

   Запуск: node check-numbers.mjs
   Возвращает ненулевой код, если сломалась связка или всплыла запрещённая
   строка. Расхождения, которые нельзя решить без финмодели, печатаются
   отдельным блоком «требует решения» и код возврата не меняют. */

import { readFileSync } from 'node:fs'

const src = readFileSync(new URL('./content.js', import.meta.url), 'utf8')
const slides = Object.fromEntries(
  src
    .split(/^===[ \t]*/m)
    .slice(1)
    .map((chunk) => {
      const [head, ...rest] = chunk.split('\n')
      const [kind, num] = head.split('|')[0].trim().split(/\s+/)
      return [`${kind} ${num}`, rest.join('\n')]
    })
)
const deck = src

let failed = 0
const ok = (label, pass, detail) => {
  console.log(`${pass ? '  ok  ' : ' FAIL '} ${label}${detail ? ': ' + detail : ''}`)
  if (!pass) failed++
}
const near = (a, b, eps = 1) => Math.abs(a - b) <= eps

console.log('Связки внутри финансовой части\n')

// Слайд 7: $179 минус себестоимость минус резерв на возвраты = вклад.
const contribution = 179 - 11.89 - 179 * 0.07
ok('вклад с программы = $179 − $11,89 − 7%', near(contribution, 155, 1),
   `$${contribution.toFixed(2)} против заявленных $155`)

// Слайд 7: потолок CAC = LTV / 3 в обоих сценариях.
ok('нижняя граница потолка CAC = $188 / 3', near(188 / 3, 63, 1),
   `$${(188 / 3).toFixed(0)} против заявленных $63`)
ok('верхняя граница потолка CAC = $249 / 3', near(249 / 3, 83, 1),
   `$${(249 / 3).toFixed(0)} против заявленных $83`)

// Заголовок слайда 7 повторяет два числа, которые стоят крупно на нём же.
const s7 = slides['slide 7'] || ''
ok('заголовок слайда 7 совпадает с крупными числами',
   /\$155/.test(s7.split('\n')[0]) && /\$63/.test(s7.split('\n')[0]) &&
   /\[big\] \$155/.test(s7) && /\[big\] \$63/.test(s7))

// Порог, вынесенный в заголовок слайда 11, должен совпадать с первым порогом
// в его же таблице.
const s11 = slides['slide 11'] || ''
ok('порог из заголовка слайда 11 стоит первым в таблице порогов',
   /\$75/.test(s11.split('\n')[0]) && /\|\s*ниже \$75\s*\|/.test(s11))

// Верхний порог должен совпадать с воротами на финальном слайде.
const s14 = slides['slide 14'] || ''
ok('верхний порог совпадает с воротами финального слайда',
   /выше \$150/.test(s11) && /Выше \$150/.test(s14))

// Строки таблицы капитала: колонка «при CAC $75» не растёт, колонка «$150» растёт.
const rows = [...s14.matchAll(/\|\s*([^|]+?)\s*\|\s*\$(\d+)k\s*\|\s*\$(\d+)k\s*\|/g)].map((m) => ({
  name: m[1], low: Number(m[2]), high: Number(m[3]),
}))
ok('в таблице капитала три рубежа', rows.length === 3, `найдено ${rows.length}`)
ok('колонка «при CAC $75» одинакова по всем рубежам',
   rows.length === 3 && new Set(rows.map((r) => r.low)).size === 1,
   rows.map((r) => '$' + r.low + 'k').join(' · '))
ok('колонка «при CAC $150» растёт от рубежа к рубежу',
   rows.length === 3 && rows[0].high < rows[1].high && rows[1].high < rows[2].high,
   rows.map((r) => '$' + r.high + 'k').join(' → '))

console.log('\nЗапрещено в этой версии\n')
const banned = [
  [/20\s?000/, 'график и строка с 20 000 пользователей'],
  [/\$3,5 млн/, 'строка «20 000 × $179 ≈ $3,5 млн»'],
  [/транш/i, 'транши — сделки с ними больше нет'],
  [/раунд/i, 'слово «раунд»'],
  [/вестинг|опцион|доля в проекте/i, 'условия по доле'],
  [/0,5%/, 'порог по конверсии'],
  [/Права — у проекта/i, 'утверждение о правах на движок'],
]
for (const [re, label] of banned) {
  ok(`нет: ${label}`, !re.test(deck), re.test(deck) ? deck.match(re)[0] : '')
}

console.log('\nТребует решения — машина проверить не может\n')
const open = []

// Стоимость процентного пункта завершаемости.
const perPoint = 670 / (51 - 41)
if (!near(perPoint, 30, 2)) {
  open.push(
    `Слайд 9. Заголовок обещает $30k за процентный пункт завершаемости, ` +
      `а строки того же слайда дают $670k на разницу 51% − 41% = 10 п.п., ` +
      `то есть $${perPoint.toFixed(0)}k за пункт. Комитет разделит эти два числа. ` +
      `Нужна цифра из финмодели: либо стоимость пункта, либо разница сценариев.`
  )
}

// Цена второго протокола против цены первого.
if (/Программа — \$179/.test(slides['slide 8'] || '') && /Следующий протокол — снова программа, \$149/.test(slides['slide 8'] || '')) {
  open.push(
    'Слайд 8. Первая программа стоит $179, следующая — $149, и это цена ' +
      'годового плана поддержания. Так в ТЗ. Если это цена возврата, стоит ' +
      'сказать почему; если опечатка — поправить одну строку.'
  )
}

// Цена подписки в смоук-тесте против опубликованного лендинга.
if (/\$20\/мес/.test(s11)) {
  open.push(
    'Слайд 11. Версия B смоук-теста здесь $20/мес, а на опубликованной ' +
      'странице landing-threshold стоит $29/мес. Одно из двух надо привести ' +
      'к другому до включения трафика.'
  )
}

if (open.length === 0) console.log('  — нечего')
for (const line of open) console.log('  ?  ' + line + '\n')

console.log(failed ? `\nСломано связок: ${failed}` : '\nВсе машинно проверяемые связки сходятся.')
process.exit(failed ? 1 : 0)
