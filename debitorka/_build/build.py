def e(s):
    return escape(s, quote=False)


def head_block(label, title, lead=None):
    lead_html = f'<p class="lead">{e(lead)}</p>' if lead else ""
    return f'''<div class="head">
        <div>
          <div class="mono label">{e(label)}</div>
          <h2 class="h2">{e(title)}</h2>
        </div>
        {lead_html}
      </div>'''


def render(slug, p):
    root = "../" if slug else ""
    css = CSS.replace("{ROOT}", root)
    home = f"{root}" or "./"
    tags = "".join(f'<span class="tag tag--light">{e(t)}</span>' for t in p["tags"])
    mock = p["mock"]
    facts = "".join(f'''<div class="fact">
          <div class="h1num">{e(n)}</div>
          <p>{e(t)}</p>
          <div class="src">{src}</div>
        </div>''' for n, t, src in p["facts"])
    pains = "".join(f'''<div class="card">
          <span class="mono who">{e(w)}</span>
          <p class="h6">{e(t)}</p>
        </div>''' for w, t in p["pains"])
